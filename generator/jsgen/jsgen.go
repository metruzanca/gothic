// Package jsgen emits the client JavaScript module for the gothic subset.
package jsgen

import (
	"encoding/json"
	"fmt"
	"go/ast"
	"go/token"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/metruzanca/gothic/parser"
)

// Options controls a single generated JavaScript module.
type Options struct {
	FileName string
	// RuntimeURL is the URL of the embedded client runtime module.
	RuntimeURL string
}

// Generate renders the JavaScript module for f.
func Generate(f *parser.File, opts Options) ([]byte, error) {
	if err := parser.Validate(f); err != nil {
		return nil, fmt.Errorf("%s: %w", opts.FileName, err)
	}
	if opts.RuntimeURL == "" {
		opts.RuntimeURL = "/_gothic/runtime.js"
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gothic from %s. DO NOT EDIT.\n\n", filepath.Base(opts.FileName))
	fmt.Fprintf(&b, "import { readState, signal, each, on, rpc } from %s;\n\n", jsString(opts.RuntimeURL))
	for _, p := range f.Procedures {
		fmt.Fprintf(&b, "const %s = (...args) => rpc(%s, ...args);\n", p.Name, jsString(p.Name))
	}
	if len(f.Procedures) > 0 {
		b.WriteString("\n")
	}
	b.WriteString("export function hydrate() {\n")

	for _, t := range f.Templates {
		g := &gen{
			f:      f,
			t:      t,
			rootID: strings.ToLower(t.Name),
			state:  map[string]bool{},
		}
		for _, sd := range t.State {
			g.state[sd.Name] = true
		}
		if err := g.emitTemplate(&b); err != nil {
			return nil, fmt.Errorf("%s: %w", opts.FileName, err)
		}
	}
	b.WriteString("}\n\nhydrate();\n")
	return []byte(b.String()), nil
}

type gen struct {
	f      *parser.File
	t      *parser.Template
	rootID string
	state  map[string]bool
	eachN  int
	eventN int
	varN   int
	tempN  int
	render strings.Builder
}

type exprCtx struct {
	locals map[string]bool
	async  bool
}

func (g *gen) emitTemplate(b *strings.Builder) error {
	g.render.Reset()
	fmt.Fprintf(b, "  // %s\n  {\n", g.t.Name)
	fmt.Fprintf(b, "    const root = document.querySelector('[data-gothic-root=%s]');\n", jsString(g.rootID))
	b.WriteString("    if (root) {\n")
	fmt.Fprintf(b, "      const state = readState(%s);\n", jsString(g.rootID))
	for _, sd := range g.t.State {
		init, err := g.expr(sd.Init, exprCtx{locals: map[string]bool{}})
		if err != nil {
			return fmt.Errorf("state %s: %w", sd.Name, err)
		}
		fmt.Fprintf(b, "      const %s = signal(%s);\n", sd.Name, init)
	}
	for _, n := range g.t.Children {
		if err := g.emitNode(b, n, false); err != nil {
			return err
		}
	}
	b.WriteString("    }\n  }\n\n")
	b.WriteString(g.render.String())
	return nil
}

func (g *gen) emitNode(b *strings.Builder, n parser.Node, inFor bool) error {
	switch n := n.(type) {
	case *parser.Element:
		for _, attr := range n.Attributes {
			ev, ok := attr.(*parser.EventAttr)
			if !ok {
				continue
			}
			if inFor {
				return fmt.Errorf("event handlers inside for are not supported in iteration 1")
			}
			if err := g.emitEvent(b, ev); err != nil {
				return err
			}
		}
		for _, child := range n.Children {
			if err := g.emitNode(b, child, inFor); err != nil {
				return err
			}
		}
	case *parser.For:
		if inFor {
			return fmt.Errorf("nested for is not supported in iteration 1")
		}
		return g.emitFor(b, n)
	case *parser.Interpolation:
		if !inFor {
			return fmt.Errorf("top-level expressions are not supported in iteration 1; use a for loop")
		}
	case *parser.Text:
	default:
		return fmt.Errorf("unsupported node type %T", n)
	}
	return nil
}

func (g *gen) emitEvent(b *strings.Builder, ev *parser.EventAttr) error {
	if ev.Fn == nil || ev.Fn.Type == nil {
		return fmt.Errorf("invalid event handler")
	}
	if ev.Fn.Type.Params != nil && len(ev.Fn.Type.Params.List) != 0 {
		return fmt.Errorf("event handlers must not take parameters")
	}
	if ev.Fn.Type.Results != nil && len(ev.Fn.Type.Results.List) != 0 {
		return fmt.Errorf("event handlers must not return values")
	}
	idx := g.eventN
	g.eventN++
	event := strings.TrimPrefix(ev.Name, "on")
	fmt.Fprintf(b, "      on(root, %s, %s, async () => {\n", jsString(fmt.Sprintf("%d", idx)), jsString(event))
	ctx := &exprCtx{locals: map[string]bool{}, async: true}
	for _, st := range ev.Fn.Body.List {
		if err := g.stmt(b, st, ctx, 4); err != nil {
			return err
		}
	}
	b.WriteString("      });\n")
	return nil
}

func (g *gen) emitFor(b *strings.Builder, f *parser.For) error {
	id, ok := f.X.(*ast.Ident)
	if !ok || !g.state[id.Name] {
		return fmt.Errorf("for range must range over a state identifier")
	}
	idx := g.eachN
	g.eachN++
	renderName := fmt.Sprintf("%sRenderEach%d", g.rootID, idx)
	if err := g.emitRender(renderName, f); err != nil {
		return err
	}
	fmt.Fprintf(b, "      each(root, %s, %s, %s);\n", jsString(fmt.Sprintf("%d", idx)), id.Name, renderName)
	return nil
}

func (g *gen) emitRender(name string, f *parser.For) error {
	params := []string{}
	ctx := exprCtx{locals: map[string]bool{}}
	if f.Key != "" && f.Key != "_" {
		params = append(params, f.Key)
		ctx.locals[f.Key] = true
	} else {
		params = append(params, "_index")
	}
	if f.Value != "" {
		params = append(params, f.Value)
		ctx.locals[f.Value] = true
	}

	var sb strings.Builder
	fmt.Fprintf(&sb, "function %s(%s) {\n", name, strings.Join(params, ", "))
	g.varN = 0
	var rootVar string
	for _, child := range f.Children {
		el, ok := child.(*parser.Element)
		if !ok {
			continue
		}
		var err error
		rootVar, err = g.emitDOM(&sb, el, ctx)
		if err != nil {
			return err
		}
	}
	if rootVar == "" {
		fmt.Fprintf(&sb, "  throw new Error(%s);\n", jsString("iteration 1 for requires one element child"))
	} else {
		fmt.Fprintf(&sb, "  return %s;\n", rootVar)
	}
	sb.WriteString("}\n\n")
	g.render.WriteString(sb.String())
	return nil
}

func (g *gen) emitDOM(sb *strings.Builder, el *parser.Element, ctx exprCtx) (string, error) {
	v := fmt.Sprintf("e%d", g.varN)
	g.varN++
	fmt.Fprintf(sb, "  const %s = document.createElement(%s);\n", v, jsString(el.Name))
	for _, attr := range el.Attributes {
		switch a := attr.(type) {
		case *parser.ConstantAttr:
			if a.Value != "" {
				fmt.Fprintf(sb, "  %s.setAttribute(%s, %s);\n", v, jsString(a.Name), jsString(a.Value))
			}
		case *parser.EventAttr:
			return "", fmt.Errorf("event handlers inside for are not supported in iteration 1")
		}
	}
	for _, child := range el.Children {
		switch c := child.(type) {
		case *parser.Text:
			fmt.Fprintf(sb, "  %s.appendChild(document.createTextNode(%s));\n", v, jsString(c.Value))
		case *parser.Interpolation:
			e, err := g.expr(c.Expr, ctx)
			if err != nil {
				return "", err
			}
			fmt.Fprintf(sb, "  %s.appendChild(document.createTextNode(String(%s)));\n", v, e)
		case *parser.Element:
			childVar, err := g.emitDOM(sb, c, ctx)
			if err != nil {
				return "", err
			}
			fmt.Fprintf(sb, "  %s.appendChild(%s);\n", v, childVar)
		case *parser.For:
			return "", fmt.Errorf("nested for is not supported in iteration 1")
		}
	}
	return v, nil
}

func (g *gen) stmt(b *strings.Builder, s ast.Stmt, ctx *exprCtx, indent int) error {
	pad := strings.Repeat("  ", indent)
	switch s := s.(type) {
	case *ast.AssignStmt:
		return g.assign(b, s, ctx, pad)
	case *ast.IfStmt:
		cond, err := g.expr(s.Cond, *ctx)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%sif (%s) {\n", pad, cond)
		for _, st := range s.Body.List {
			if err := g.stmt(b, st, ctx, indent+1); err != nil {
				return err
			}
		}
		fmt.Fprintf(b, "%s}", pad)
		if s.Else != nil {
			block, ok := s.Else.(*ast.BlockStmt)
			if !ok {
				return fmt.Errorf("else-if is not supported in iteration 1")
			}
			b.WriteString(" else {\n")
			for _, st := range block.List {
				if err := g.stmt(b, st, ctx, indent+1); err != nil {
					return err
				}
			}
			fmt.Fprintf(b, "%s}", pad)
		}
		b.WriteString("\n")
		return nil
	case *ast.ReturnStmt:
		if len(s.Results) == 0 {
			fmt.Fprintf(b, "%sreturn;\n", pad)
			return nil
		}
		if len(s.Results) != 1 {
			return fmt.Errorf("multiple return values are not supported")
		}
		e, err := g.expr(s.Results[0], *ctx)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%sreturn %s;\n", pad, e)
		return nil
	case *ast.ExprStmt:
		e, err := g.expr(s.X, *ctx)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%s%s;\n", pad, e)
		return nil
	case *ast.BlockStmt:
		for _, st := range s.List {
			if err := g.stmt(b, st, ctx, indent); err != nil {
				return err
			}
		}
		return nil
	default:
		return fmt.Errorf("unsupported statement %T", s)
	}
}

func (g *gen) assign(b *strings.Builder, s *ast.AssignStmt, ctx *exprCtx, pad string) error {
	if len(s.Lhs) == 2 && len(s.Rhs) == 1 && s.Tok == token.DEFINE {
		call, ok := s.Rhs[0].(*ast.CallExpr)
		if !ok {
			return fmt.Errorf("two-value assignment requires a procedure call")
		}
		valueName, ok := identName(s.Lhs[0])
		if !ok {
			return fmt.Errorf("two-value assignment requires identifiers")
		}
		errName, ok := identName(s.Lhs[1])
		if !ok {
			return fmt.Errorf("two-value assignment requires identifiers")
		}
		callExpr, err := g.expr(call, *ctx)
		if err != nil {
			return err
		}
		tmp := g.temp()
		fmt.Fprintf(b, "%slet %s, %s;\n", pad, valueName, errName)
		fmt.Fprintf(b, "%stry {\n", pad)
		fmt.Fprintf(b, "%s  %s = %s;\n", pad, valueName, callExpr)
		fmt.Fprintf(b, "%s} catch (%s) {\n", pad, tmp)
		fmt.Fprintf(b, "%s  %s = %s;\n", pad, errName, tmp)
		fmt.Fprintf(b, "%s}\n", pad)
		ctx.locals[valueName] = true
		ctx.locals[errName] = true
		return nil
	}

	if len(s.Lhs) != 1 || len(s.Rhs) != 1 {
		return fmt.Errorf("only single-value assignment is supported")
	}
	lhs, rhs := s.Lhs[0], s.Rhs[0]
	if s.Tok == token.DEFINE {
		name, ok := identName(lhs)
		if !ok {
			return fmt.Errorf("short declaration requires an identifier")
		}
		e, err := g.expr(rhs, *ctx)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%sconst %s = %s;\n", pad, name, e)
		ctx.locals[name] = true
		return nil
	}
	if s.Tok != token.ASSIGN {
		return fmt.Errorf("unsupported assignment operator %s", s.Tok)
	}
	id, ok := lhs.(*ast.Ident)
	if !ok {
		return fmt.Errorf("only identifier assignment is supported")
	}
	if g.state[id.Name] {
		if call, ok := rhs.(*ast.CallExpr); ok && isAppend(call) {
			if first, ok := call.Args[0].(*ast.Ident); ok && first.Name == id.Name {
				args := make([]string, 0, len(call.Args)-1)
				for _, a := range call.Args[1:] {
					e, err := g.expr(a, *ctx)
					if err != nil {
						return err
					}
					args = append(args, e)
				}
				fmt.Fprintf(b, "%s%s.push(%s);\n", pad, id.Name, strings.Join(args, ", "))
				return nil
			}
		}
		e, err := g.expr(rhs, *ctx)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%s%s.set(%s);\n", pad, id.Name, e)
		return nil
	}
	e, err := g.expr(rhs, *ctx)
	if err != nil {
		return err
	}
	fmt.Fprintf(b, "%s%s = %s;\n", pad, id.Name, e)
	return nil
}

func (g *gen) expr(e ast.Expr, ctx exprCtx) (string, error) {
	switch e := e.(type) {
	case *ast.Ident:
		if e.Name == "nil" {
			return "null", nil
		}
		if ctx.locals[e.Name] {
			return e.Name, nil
		}
		if g.state[e.Name] {
			return e.Name + "()", nil
		}
		return e.Name, nil
	case *ast.BasicLit:
		switch e.Kind {
		case token.STRING:
			v, err := strconv.Unquote(e.Value)
			if err != nil {
				return "", err
			}
			return jsString(v), nil
		case token.INT, token.FLOAT:
			return e.Value, nil
		case token.CHAR:
			v, err := strconv.Unquote(e.Value)
			if err != nil {
				return "", err
			}
			return jsString(v), nil
		default:
			return "", fmt.Errorf("unsupported literal %s", e.Value)
		}
	case *ast.SelectorExpr:
		if e.Sel.Name == "Error" {
			x, err := g.expr(e.X, ctx)
			if err != nil {
				return "", err
			}
			return x + ".message", nil
		}
		x, err := g.expr(e.X, ctx)
		if err != nil {
			return "", err
		}
		return x + "." + e.Sel.Name, nil
	case *ast.CallExpr:
		if sel, ok := e.Fun.(*ast.SelectorExpr); ok {
			if sel.Sel.Name == "Error" && len(e.Args) == 0 {
				x, err := g.expr(sel.X, ctx)
				if err != nil {
					return "", err
				}
				return x + ".message", nil
			}
			if id, ok := sel.X.(*ast.Ident); ok && id.Name == "api" {
				return "", fmt.Errorf("call procedures directly by name, for example %s(), not api.%s()", sel.Sel.Name, sel.Sel.Name)
			}
		}
		if id, ok := e.Fun.(*ast.Ident); ok {
			if id.Name == "append" {
				return "", fmt.Errorf("append is only supported in state assignment")
			}
			if g.isProc(id.Name) && !ctx.locals[id.Name] {
				if !ctx.async {
					return "", fmt.Errorf("procedure calls are only supported in event handlers")
				}
				args, err := g.exprs(e.Args, ctx)
				if err != nil {
					return "", err
				}
				return fmt.Sprintf("await %s(%s)", id.Name, strings.Join(args, ", ")), nil
			}
		}
		fun, err := g.expr(e.Fun, ctx)
		if err != nil {
			return "", err
		}
		args, err := g.exprs(e.Args, ctx)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("%s(%s)", fun, strings.Join(args, ", ")), nil
	case *ast.BinaryExpr:
		x, err := g.expr(e.X, ctx)
		if err != nil {
			return "", err
		}
		y, err := g.expr(e.Y, ctx)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("%s %s %s", x, e.Op.String(), y), nil
	case *ast.UnaryExpr:
		x, err := g.expr(e.X, ctx)
		if err != nil {
			return "", err
		}
		return e.Op.String() + x, nil
	case *ast.ParenExpr:
		x, err := g.expr(e.X, ctx)
		if err != nil {
			return "", err
		}
		return "(" + x + ")", nil
	case *ast.CompositeLit:
		return g.composite(e, ctx)
	case *ast.IndexExpr:
		x, err := g.expr(e.X, ctx)
		if err != nil {
			return "", err
		}
		i, err := g.expr(e.Index, ctx)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("%s[%s]", x, i), nil
	case *ast.SliceExpr:
		x, err := g.expr(e.X, ctx)
		if err != nil {
			return "", err
		}
		lo, hi := "", ""
		if e.Low != nil {
			lo, err = g.expr(e.Low, ctx)
			if err != nil {
				return "", err
			}
		}
		if e.High != nil {
			hi, err = g.expr(e.High, ctx)
			if err != nil {
				return "", err
			}
		}
		return fmt.Sprintf("%s.slice(%s, %s)", x, orZero(lo), orZero(hi)), nil
	case *ast.FuncLit:
		return "", fmt.Errorf("function literals are only supported as event handlers")
	default:
		return "", fmt.Errorf("unsupported expression %T", e)
	}
}

func (g *gen) composite(e *ast.CompositeLit, ctx exprCtx) (string, error) {
	at, ok := e.Type.(*ast.ArrayType)
	if !ok {
		return "", fmt.Errorf("only slice literals are supported in state initializers")
	}
	if at.Len != nil {
		return "", fmt.Errorf("only slice literals are supported in state initializers")
	}
	parts := make([]string, 0, len(e.Elts))
	for _, el := range e.Elts {
		x, err := g.expr(el, ctx)
		if err != nil {
			return "", err
		}
		parts = append(parts, x)
	}
	return "[" + strings.Join(parts, ", ") + "]", nil
}

func (g *gen) exprs(args []ast.Expr, ctx exprCtx) ([]string, error) {
	out := make([]string, 0, len(args))
	for _, a := range args {
		x, err := g.expr(a, ctx)
		if err != nil {
			return nil, err
		}
		out = append(out, x)
	}
	return out, nil
}

func (g *gen) isProc(name string) bool {
	for _, p := range g.f.Procedures {
		if p.Name == name {
			return true
		}
	}
	return false
}

func (g *gen) temp() string {
	g.tempN++
	return fmt.Sprintf("__gothicErr%d", g.tempN)
}

func identName(e ast.Expr) (string, bool) {
	id, ok := e.(*ast.Ident)
	if !ok {
		return "", false
	}
	return id.Name, true
}

func isAppend(c *ast.CallExpr) bool {
	id, ok := c.Fun.(*ast.Ident)
	return ok && id.Name == "append" && len(c.Args) >= 2
}

func orZero(s string) string {
	if s == "" {
		return "0"
	}
	return s
}

func jsString(s string) string {
	b, err := json.Marshal(s)
	if err != nil {
		return `""`
	}
	return string(b)
}
