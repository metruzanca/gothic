// Package jsgen emits the client JavaScript module for the iteration 1 subset.
package jsgen

import (
	"encoding/json"
	"fmt"
	"strings"

	"github.com/metruzanca/gothic/parser"
)

// Options controls a single generated JavaScript module.
type Options struct {
	FileName string
	// RuntimeURL is the URL of the embedded client runtime module.
	RuntimeURL string
}

// Generate renders the JavaScript module for f.
func Generate(f *parser.File, opts Options) ([]byte, error) {
	if opts.RuntimeURL == "" {
		opts.RuntimeURL = "/_gothic/runtime.js"
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gothic from %s. DO NOT EDIT.\n\n", opts.FileName)
	fmt.Fprintf(&b, "import { readState, signal, each, on, rpc } from %s;\n\n", jsString(opts.RuntimeURL))
	b.WriteString("export function hydrate() {\n")

	for _, t := range f.Templates {
		g := &gen{f: f, t: t, rootID: strings.ToLower(t.Name)}
		if err := g.emitTemplate(&b); err != nil {
			return nil, fmt.Errorf("%s: %w", opts.FileName, err)
		}
	}
	b.WriteString("}\n\nhydrate();\n")
	return []byte(b.String()), nil
}

type gen struct {
	f      *parser.File
	t      *parser.Template
	rootID string
	eachN  int
	eventN int
	render strings.Builder
	varN   int
}

func (g *gen) emitTemplate(b *strings.Builder) error {
	g.render.Reset()
	fmt.Fprintf(b, "  // %s\n", g.t.Name)
	b.WriteString("  {\n")
	fmt.Fprintf(b, "    const root = document.querySelector('[data-gothic-root=%s]');\n", jsString(g.rootID))
	b.WriteString("    if (root) {\n")
	fmt.Fprintf(b, "      const state = readState(%s);\n", jsString(g.rootID))
	for _, sd := range g.t.State {
		fmt.Fprintf(b, "      const %s = signal(state[%s] ?? []);\n", sd.Name, jsString(sd.Name))
	}
	b.WriteString("      const api = {\n")
	for _, p := range g.f.Procedures {
		fmt.Fprintf(b, "        %s: (...args) => rpc(%s, ...args),\n", p.Name, jsString(p.Name))
	}
	b.WriteString("      };\n")

	for _, n := range g.t.Children {
		if err := g.emitNode(b, n, false); err != nil {
			return err
		}
	}
	b.WriteString("    }\n  }\n\n")
	b.WriteString(g.render.String())
	return nil
}

func (g *gen) emitNode(b *strings.Builder, n parser.Node, inEach bool) error {
	switch n := n.(type) {
	case *parser.Element:
		for _, attr := range n.Attributes {
			ev, ok := attr.(*parser.EventAttr)
			if !ok {
				continue
			}
			if inEach {
				return fmt.Errorf("event handlers inside @each are not supported in iteration 1")
			}
			g.emitEvent(b, ev)
		}
		for _, child := range n.Children {
			if err := g.emitNode(b, child, inEach); err != nil {
				return err
			}
		}
	case *parser.Each:
		if inEach {
			return fmt.Errorf("nested @each is not supported in iteration 1")
		}
		idx := g.eachN
		g.eachN++
		renderName := fmt.Sprintf("%sRenderEach%d", g.rootID, idx)
		g.emitRender(renderName, n)
		fmt.Fprintf(b, "      each(root, %s, %s, %s);\n", jsString(fmt.Sprintf("%d", idx)), n.List, renderName)
		// Events inside each are rejected when the renderer is built.
	case *parser.Expr:
		if !inEach {
			return fmt.Errorf("top-level expressions are not supported in iteration 1; use @each")
		}
	case *parser.Text:
		// Static text is already server rendered.
	default:
		return fmt.Errorf("unsupported node type %T", n)
	}
	return nil
}

func (g *gen) emitEvent(b *strings.Builder, ev *parser.EventAttr) {
	idx := g.eventN
	g.eventN++
	event := strings.TrimPrefix(ev.Name, "on")
	fmt.Fprintf(b, "      on(root, %s, %s, async () => {\n", jsString(fmt.Sprintf("%d", idx)), jsString(event))
	for _, stmt := range ev.Body {
		switch s := stmt.(type) {
		case *parser.HandlerCall:
			fmt.Fprintf(b, "        %s;\n", g.callExpr(s))
		case *parser.HandlerAwaitAssign:
			fmt.Fprintf(b, "        const %s = await %s;\n", s.Name, g.callExpr(&s.Call))
		}
	}
	b.WriteString("      });\n")
}

func (g *gen) callExpr(c *parser.HandlerCall) string {
	target := c.Target
	for _, sd := range g.t.State {
		if target == sd.Name+".Push" {
			target = sd.Name + ".push"
		}
	}
	args := make([]string, len(c.Args))
	for i, a := range c.Args {
		if a.IsString {
			args[i] = jsString(a.Value)
		} else {
			args[i] = a.Value
		}
	}
	return target + "(" + strings.Join(args, ", ") + ")"
}

func (g *gen) emitRender(name string, e *parser.Each) {
	if len(e.Children) != 1 {
		// Keep the demo honest: one root element per each item.
	}
	var sb strings.Builder
	fmt.Fprintf(&sb, "function %s(%s) {\n", name, e.Var)
	g.varN = 0
	var rootVar string
	for _, child := range e.Children {
		el, ok := child.(*parser.Element)
		if !ok {
			continue
		}
		rootVar = g.emitDOM(&sb, el, e.Var)
	}
	if rootVar == "" {
		fmt.Fprintf(&sb, "  throw new Error(%s);\n", jsString("iteration 1 @each requires one element child"))
	} else {
		fmt.Fprintf(&sb, "  return %s;\n", rootVar)
	}
	sb.WriteString("}\n\n")
	g.render.WriteString(sb.String())
	_ = name
}

func (g *gen) emitDOM(sb *strings.Builder, el *parser.Element, scopeVar string) string {
	v := fmt.Sprintf("e%d", g.varN)
	g.varN++
	fmt.Fprintf(sb, "  const %s = document.createElement(%s);\n", v, jsString(el.Name))
	for _, attr := range el.Attributes {
		switch a := attr.(type) {
		case *parser.ConstantAttr:
			if a.Value != "" {
				fmt.Fprintf(sb, "  %s.setAttribute(%s, %s);\n", v, jsString(a.Name), jsString(a.Value))
			}
		}
	}
	for _, child := range el.Children {
		switch c := child.(type) {
		case *parser.Text:
			fmt.Fprintf(sb, "  %s.appendChild(document.createTextNode(%s));\n", v, jsString(c.Value))
		case *parser.Expr:
			fmt.Fprintf(sb, "  %s.appendChild(document.createTextNode(String(%s)));\n", v, c.Value)
		case *parser.Element:
			childVar := g.emitDOM(sb, c, scopeVar)
			fmt.Fprintf(sb, "  %s.appendChild(%s);\n", v, childVar)
		}
	}
	_ = scopeVar
	return v
}

func jsString(s string) string {
	b, err := json.Marshal(s)
	if err != nil {
		return `""`
	}
	return string(b)
}
