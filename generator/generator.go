// Package generator emits Go server code for the iteration 1 subset.
package generator

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	goparser "go/parser"
	"go/token"
	"html"
	"sort"
	"strconv"
	"strings"

	"github.com/metruzanca/gothic/goapp"
	"github.com/metruzanca/gothic/parser"
)

func wrapFile(file string, err error) error {
	var pe *parser.Error
	if errors.As(err, &pe) {
		return err
	}
	return fmt.Errorf("%s: %w", file, err)
}

// Options controls a single generated .gth file.
type Options struct {
	// FileName is the source file name, used in the generated header.
	FileName string
	// ModuleBase is the output base name, for example pingpong.
	ModuleBase string
	// App is set for Bubble Tea-style app views.
	App *goapp.App
	// Stateful lists app-local stateful components used by the app.
	Stateful []*Stateful
}

// Stateful is a stateful component rendered as an island.
type Stateful struct {
	Name        string
	ViewName    string
	GoName      string
	MountFunc   string
	CreateFunc  string
	ModelType   string
	ModelJSON   string
	PropsType   string
	Props       []parser.Param
	View        *parser.Template
	App         *goapp.App
	Listable    bool
	External    bool
	ImportAlias string
	ImportPath  string
	ModuleURL   string
}

// PropsGoType returns the Go type used for the component props, qualified for
// external components.
func (c *Stateful) PropsGoType() string {
	if c.PropsType == "" {
		return ""
	}
	if c.External {
		return c.ImportAlias + "." + c.PropsType
	}
	return c.PropsType
}

// ComponentsModuleFileName returns the generated JavaScript file name for app components.
func ComponentsModuleFileName(base string) string {
	return base + "_components_gothic.js"
}

// ComponentsModuleURL returns the URL at which the app component module is served.
func ComponentsModuleURL(base string) string {
	return "/_gothic/modules/" + ComponentsModuleFileName(base)
}

// RootID returns the stable hydration root id for a template.
func RootID(templateName string) string {
	return strings.ToLower(templateName)
}

// ModuleFileName returns the generated JavaScript file name for a base.
func ModuleFileName(base string) string {
	return base + "_gothic.js"
}

// ModuleURL returns the URL at which the generated module is served.
func ModuleURL(base string) string {
	return "/_gothic/modules/" + ModuleFileName(base)
}

// Generate renders the Go source for f.
func Generate(f *parser.File, opts Options) ([]byte, error) {
	body, usesHTML, usesFmt, err := generateBody(f, opts)
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString("// Code generated by gothic. DO NOT EDIT.\n\n")
	b.WriteString("package " + f.Package + "\n\n")
	imports, err := mergeImports(nil, viewImports(usesHTML, usesFmt))
	if err != nil {
		return nil, wrapFile(opts.FileName, err)
	}
	writeImportBlock(&b, imports)
	b.WriteString(body)
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("%s: formatting generated Go: %w", opts.FileName, err)
	}
	return formatted, nil
}

// GenerateSingle merges the Go prelude and the generated view into one file.
func GenerateSingle(f *parser.File, app *goapp.App, opts Options) ([]byte, error) {
	if len(f.Templates) != 1 {
		return nil, fmt.Errorf("%s: GenerateSingle expects one expanded App view", opts.FileName)
	}
	body, usesHTML, usesFmt, err := generateBody(f, opts)
	if err != nil {
		return nil, err
	}

	fset := token.NewFileSet()
	file, err := goparser.ParseFile(fset, opts.FileName, app.Source, goparser.ParseComments)
	if err != nil {
		return nil, fmt.Errorf("%s: parsing prelude: %w", opts.FileName, err)
	}
	for _, group := range file.Comments {
		for _, comment := range group.List {
			if comment.Pos() < file.Package {
				if strings.HasPrefix(comment.Text, "//go:build") || strings.HasPrefix(comment.Text, "// +build") {
					return nil, fmt.Errorf("%s: build constraints in the prelude are not supported yet", opts.FileName)
				}
			}
		}
	}

	preludeImports := make([]importSpec, 0, len(file.Imports))
	for _, imp := range file.Imports {
		name := ""
		if imp.Name != nil {
			name = imp.Name.Name
		}
		preludeImports = append(preludeImports, importSpec{Name: name, Path: imp.Path.Value})
	}
	viewSpecs := viewImports(usesHTML, usesFmt)
	seenExternal := map[string]bool{}
	for _, comp := range opts.Stateful {
		if !comp.External {
			continue
		}
		key := comp.ImportAlias + " " + comp.ImportPath
		if seenExternal[key] {
			continue
		}
		seenExternal[key] = true
		viewSpecs = append(viewSpecs, importSpec{Name: comp.ImportAlias, Path: strconv.Quote(comp.ImportPath)})
	}
	imports, err := mergeImports(preludeImports, viewSpecs)
	if err != nil {
		return nil, wrapFile(opts.FileName, err)
	}

	var start token.Pos
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if ok && gen.Tok == token.IMPORT {
			start = gen.End()
		}
	}
	if start == token.NoPos {
		start = file.Name.End()
	}
	offset := fset.Position(start).Offset
	if offset < 0 || offset > len(app.Source) {
		return nil, fmt.Errorf("%s: invalid prelude offset", opts.FileName)
	}
	decls := app.Source[offset:]

	var b strings.Builder
	b.WriteString("// Code generated by gothic. DO NOT EDIT.\n\n")
	b.WriteString("package " + file.Name.Name + "\n\n")
	writeImportBlock(&b, imports)
	b.Write(decls)
	if len(decls) == 0 || decls[len(decls)-1] != '\n' {
		b.WriteString("\n")
	}
	b.WriteString("\n")
	b.WriteString(body)

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("%s: formatting generated Go: %w", opts.FileName, err)
	}
	return formatted, nil
}

func generateBody(f *parser.File, opts Options) (string, bool, bool, error) {
	if err := parser.Validate(f); err != nil {
		return "", false, false, wrapFile(opts.FileName, err)
	}
	if len(f.Templates) == 0 {
		return "", false, false, fmt.Errorf("%s: no template to generate", opts.FileName)
	}

	var body strings.Builder
	usesHTML := false
	usesFmt := false
	for _, t := range f.Templates {
		g := &templateGen{
			t:             t,
			rootID:        RootID(t.Name),
			moduleURL:     ModuleURL(opts.ModuleBase),
			appRoot:       true,
			allowStateful: true,
			stateful:      statefulMap(opts.Stateful),
		}
		code, err := g.generate()
		if err != nil {
			return "", false, false, wrapFile(opts.FileName, err)
		}
		if g.usesHTML {
			usesHTML = true
		}
		if g.usesFmt {
			usesFmt = true
		}
		body.WriteString(code)
		body.WriteString("\n")
	}

	for _, comp := range opts.Stateful {
		if comp.External {
			continue
		}
		viewGen := &templateGen{
			t:             comp.View,
			funcName:      comp.ViewName,
			appRoot:       false,
			allowStateful: false,
		}
		code, err := viewGen.generateComponentView()
		if err != nil {
			return "", false, false, wrapFile(opts.FileName, err)
		}
		if viewGen.usesHTML {
			usesHTML = true
		}
		if viewGen.usesFmt {
			usesFmt = true
		}
		body.WriteString(code)
		body.WriteString("\n")
		writeStatefulWrapper(&body, comp)
	}

	embedName := sanitizeIdent(opts.ModuleBase) + "JS"
	body.WriteString("//go:embed " + ModuleFileName(opts.ModuleBase) + "\n")
	body.WriteString("var " + embedName + " []byte\n\n")
	body.WriteString("func init() {\n")
	body.WriteString("\tgothic.RegisterModule(" + strconv.Quote(ModuleURL(opts.ModuleBase)) + ", " + embedName + ")\n")
	body.WriteString("}\n\n")

	localStateful := false
	for _, comp := range opts.Stateful {
		if !comp.External {
			localStateful = true
			break
		}
	}
	if localStateful {
		usesHTML = true
		compFile := ComponentsModuleFileName(opts.ModuleBase)
		compURL := ComponentsModuleURL(opts.ModuleBase)
		compEmbed := sanitizeIdent(opts.ModuleBase) + "ComponentsJS"
		body.WriteString("//go:embed " + compFile + "\n")
		body.WriteString("var " + compEmbed + " []byte\n\n")
		body.WriteString("func init() {\n")
		body.WriteString("\tgothic.RegisterModule(" + strconv.Quote(compURL) + ", " + compEmbed + ")\n")
		body.WriteString("}\n\n")
	}

	switch {
	case opts.App != nil && opts.App.ProceduresType != "":
		writeAppRegistrar(&body, opts.App)
	case len(f.Procedures) > 0:
		writeRegistrar(&body, f)
	}
	return body.String(), usesHTML, usesFmt, nil
}

type importSpec struct {
	Name string
	Path string
}

func viewImports(usesHTML, usesFmt bool) []importSpec {
	specs := []importSpec{
		{Path: `"context"`},
		{Path: `"encoding/json"`},
		{Path: `"io"`},
		{Name: "_", Path: `"embed"`},
		{Path: `"github.com/metruzanca/gothic"`},
	}
	if usesFmt {
		specs = append(specs, importSpec{Path: `"fmt"`})
	}
	if usesHTML {
		specs = append(specs, importSpec{Path: `"html"`})
	}
	return specs
}

func mergeImports(prelude, view []importSpec) ([]importSpec, error) {
	byPath := map[string]importSpec{}
	out := make([]importSpec, 0, len(prelude)+len(view))
	for _, imp := range prelude {
		byPath[imp.Path] = imp
		out = append(out, imp)
	}
	for _, imp := range view {
		existing, ok := byPath[imp.Path]
		if !ok {
			byPath[imp.Path] = imp
			out = append(out, imp)
			continue
		}
		existingName := existing.Name
		if existingName == "" {
			existingName = defaultImportName(existing.Path)
		}
		impName := imp.Name
		if impName == "" {
			impName = defaultImportName(imp.Path)
		}
		if existingName == impName {
			continue
		}
		if imp.Path == `"embed"` {
			continue
		}
		return nil, fmt.Errorf("prelude imports %s as %q, but the generated view needs %q", imp.Path, existing.Name, imp.Name)
	}
	names := map[string]string{}
	for _, imp := range out {
		name := imp.Name
		if name == "" {
			name = defaultImportName(imp.Path)
		}
		if name == "_" || name == "." {
			continue
		}
		if previous, ok := names[name]; ok && previous != imp.Path {
			return nil, fmt.Errorf("import name %q is used by both %s and %s", name, previous, imp.Path)
		}
		names[name] = imp.Path
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Path < out[j].Path })
	return out, nil
}

func defaultImportName(path string) string {
	unquoted, err := strconv.Unquote(path)
	if err != nil {
		return path
	}
	if i := strings.LastIndex(unquoted, "/"); i >= 0 {
		return unquoted[i+1:]
	}
	return unquoted
}

func writeImportBlock(b *strings.Builder, imports []importSpec) {
	b.WriteString("import (\n")
	for _, imp := range imports {
		b.WriteString("\t")
		if imp.Name != "" {
			b.WriteString(imp.Name + " ")
		}
		b.WriteString(imp.Path)
		b.WriteString("\n")
	}
	b.WriteString(")\n\n")
}

type templateGen struct {
	t             *parser.Template
	funcName      string
	rootID        string
	moduleURL     string
	appRoot       bool
	allowStateful bool
	stateful      map[string]*Stateful
	componentN    int
	eachN         int
	ifN           int
	eventN        int
	textN         int
	attrN         int
	classN        int
	focusN        int
	usesHTML      bool
	usesFmt       bool
}

func (g *templateGen) generate() (string, error) {
	if len(g.t.Children) != 1 {
		return "", parser.PosError(g.t.NodePosition, "wrap the view in one root element", "template %s must have exactly one root element", g.t.Name)
	}
	root, ok := g.t.Children[0].(*parser.Element)
	if !ok {
		return "", parser.PosError(g.t.NodePosition, "use an element as the view root", "template %s root must be an element", g.t.Name)
	}

	modelName, modelType, hasModel := singleModelParam(g.t.Params)

	var b strings.Builder
	g.writeFuncPrefix(&b, g.t.Name, paramsOrEmpty(g.t))

	for _, sd := range g.t.State {
		fmt.Fprintf(&b, "\t\t%s := %s\n", sd.Name, goExpr(sd.Init))
	}

	if g.appRoot && hasModel {
		fmt.Fprintf(&b, "\t\tstateJSON, err := json.Marshal(%s)\n", modelName)
		b.WriteString("\t\tif err != nil {\n\t\t\treturn err\n\t\t}\n")
	}

	if err := g.writeElement(&b, root, true); err != nil {
		return "", err
	}
	if g.appRoot {
		fmt.Fprintf(&b, "\t\tif err := write(%s); err != nil {\n\t\t\treturn err\n\t\t}\n", strconv.Quote("\n<script type=\"module\" src=\""+g.moduleURL+"\"></script>\n"))
	}
	b.WriteString("\t\treturn nil\n\t})\n}\n")

	if g.appRoot && hasModel {
		fmt.Fprintf(&b, "\n// View implements gothic.Model for %s.\n", modelType)
		fmt.Fprintf(&b, "func (m %s) View() gothic.Component {\n\treturn %s(m)\n}\n", modelType, g.t.Name)
	}
	return b.String(), nil
}

func (g *templateGen) generateComponentView() (string, error) {
	if len(g.t.Children) != 1 {
		return "", parser.PosError(g.t.NodePosition, "wrap the component in one root element", "component %s must have exactly one root element", g.t.Name)
	}
	root, ok := g.t.Children[0].(*parser.Element)
	if !ok {
		return "", parser.PosError(g.t.NodePosition, "use an element as the component root", "component %s root must be an element", g.t.Name)
	}
	name := g.funcName
	if name == "" {
		name = g.t.Name + "View"
	}
	var b strings.Builder
	g.writeFuncPrefix(&b, name, paramsOrEmpty(g.t))
	if err := g.writeElement(&b, root, true); err != nil {
		return "", err
	}
	b.WriteString("\t\treturn nil\n\t})\n}\n")
	return b.String(), nil
}

func (g *templateGen) writeFuncPrefix(b *strings.Builder, name, params string) {
	fmt.Fprintf(b, "func %s%s gothic.Component {\n", name, params)
	b.WriteString("\treturn gothic.ComponentFunc(func(ctx context.Context, w io.Writer) error {\n")
	b.WriteString("\t\tif err := ctx.Err(); err != nil {\n\t\t\treturn err\n\t\t}\n")
	b.WriteString("\t\twrite := func(s string) error {\n\t\t\t_, err := io.WriteString(w, s)\n\t\t\treturn err\n\t\t}\n")
}

func singleModelParam(params string) (name, typ string, ok bool) {
	p := strings.TrimSpace(params)
	p = strings.TrimPrefix(p, "(")
	p = strings.TrimSuffix(p, ")")
	p = strings.TrimSpace(p)
	if p == "" || strings.Contains(p, ",") {
		return "", "", false
	}
	parts := strings.Fields(p)
	if len(parts) != 2 {
		return "", "", false
	}
	return parts[0], parts[1], true
}

func (g *templateGen) writeElement(b *strings.Builder, el *parser.Element, isRoot bool) error {
	var static strings.Builder
	flush := func() {
		if static.Len() == 0 {
			return
		}
		g.emitWrite(b, static.String())
		static.Reset()
	}

	static.WriteString("<" + el.Name)
	if isRoot && g.appRoot {
		static.WriteString(" data-gothic-root=\"" + g.rootID + "\"")
	}

	var classToggles []classToggle
	var eventMarkers []string
	classValue := ""
	hasClass := false
	for _, attr := range el.Attributes {
		switch a := attr.(type) {
		case *parser.ConstantAttr:
			if a.Name == "class" {
				classValue = a.Value
				hasClass = true
				continue
			}
			if a.Value == "" {
				static.WriteString(" " + a.Name)
			} else {
				static.WriteString(" " + a.Name + "=\"" + html.EscapeString(a.Value) + "\"")
			}
		case *parser.EventAttr:
			eventMarkers = append(eventMarkers, fmt.Sprintf("%d", g.eventN))
			g.eventN++
		case *parser.ExprAttr:
			switch a.Name {
			case "focus":
				idx := g.focusN
				g.focusN++
				static.WriteString(fmt.Sprintf(" data-gothic-focus=\"%d\"", idx))
			case "checked":
				idx := g.attrN
				g.attrN++
				static.WriteString(fmt.Sprintf(" data-gothic-attr-%d=\"checked\"", idx))
				flush()
				fmt.Fprintf(b, "\t\tif %s {\n", goExpr(a.Expr))
				g.emitWrite(b, " checked")
				b.WriteString("\t\t}\n")
			case "value":
				idx := g.attrN
				g.attrN++
				static.WriteString(fmt.Sprintf(" data-gothic-attr-%d=\"value\"", idx))
				flush()
				g.emitWrite(b, " value=\"")
				g.emitEscapedExpr(b, a.Expr)
				g.emitWrite(b, "\"")
			default:
				idx := g.attrN
				g.attrN++
				static.WriteString(fmt.Sprintf(" data-gothic-attr-%d=%q", idx, a.Name))
				flush()
				g.emitWrite(b, " "+a.Name+"=\"")
				g.emitEscapedExpr(b, a.Expr)
				g.emitWrite(b, "\"")
			}
		case *parser.ClassToggleAttr:
			idx := g.classN
			g.classN++
			static.WriteString(fmt.Sprintf(" data-gothic-class-%d=%q", idx, a.Name))
			classToggles = append(classToggles, classToggle{Name: a.Name, Expr: a.Expr, Marker: idx})
		case *parser.RouteAttr:
			if el.Name != "a" {
				return parser.NodeError(el, "use <a href=\"/path\" route> for client-side navigation", "route is only supported on <a>")
			}
			eventMarkers = append(eventMarkers, fmt.Sprintf("%d", g.eventN))
			g.eventN++
		}
	}

	if len(eventMarkers) > 0 {
		static.WriteString(" data-gothic-on=\"" + strings.Join(eventMarkers, " ") + "\"")
	}

	if hasClass || len(classToggles) > 0 {
		flush()
		g.emitWrite(b, " class=\""+html.EscapeString(classValue))
		for _, ct := range classToggles {
			fmt.Fprintf(b, "\t\tif %s {\n", goExpr(ct.Expr))
			g.emitWrite(b, " "+ct.Name)
			b.WriteString("\t\t}\n")
		}
		g.emitWrite(b, "\"")
	}

	if el.Key != nil {
		flush()
		g.emitWrite(b, " data-gothic-key=\"")
		g.emitEscapedExpr(b, el.Key)
		g.emitWrite(b, "\"")
	}

	static.WriteString(">")
	flush()

	if isRoot && g.appRoot {
		fmt.Fprintf(b, "\t\tif err := write(%s); err != nil {\n\t\t\treturn err\n\t\t}\n", strconv.Quote("<script type=\"application/json\" data-gothic-state=\""+g.rootID+"\">"))
		b.WriteString("\t\tif _, err := w.Write(stateJSON); err != nil {\n\t\t\treturn err\n\t\t}\n")
		g.emitWrite(b, "</script>\n")
	}

	if parser.IsVoidElement(el.Name) {
		return nil
	}

	for _, child := range el.Children {
		if err := g.writeNode(b, child); err != nil {
			return err
		}
	}
	g.emitWrite(b, "</"+el.Name+">")
	return nil
}

type classToggle struct {
	Name   string
	Expr   ast.Expr
	Marker int
}

func (g *templateGen) emitEscapedExpr(b *strings.Builder, expr ast.Expr) {
	g.usesHTML = true
	g.usesFmt = true
	fmt.Fprintf(b, "\t\tif err := write(html.EscapeString(fmt.Sprint(%s))); err != nil {\n\t\t\treturn err\n\t\t}\n", goExpr(expr))
}

func (g *templateGen) writeNode(b *strings.Builder, n parser.Node) error {
	switch n := n.(type) {
	case *parser.Text:
		g.emitWrite(b, html.EscapeString(n.Value))
	case *parser.Interpolation:
		g.usesHTML = true
		g.usesFmt = true
		idx := g.textN
		g.textN++
		g.emitWrite(b, fmt.Sprintf("<!--g:text:%d:open-->", idx))
		fmt.Fprintf(b, "\t\tif err := write(html.EscapeString(fmt.Sprint(%s))); err != nil {\n\t\t\treturn err\n\t\t}\n", goExpr(n.Expr))
		g.emitWrite(b, fmt.Sprintf("<!--g:text:%d:close-->", idx))
	case *parser.Element:
		return g.writeElement(b, n, false)
	case *parser.For:
		return g.writeFor(b, n)
	case *parser.If:
		return g.writeIf(b, n)
	case *parser.Slot:
		return parser.NodeError(n, "slots are only supported in pure components; pass a prop instead", "slot is only supported in pure components")
	case *parser.ComponentCall:
		return g.writeStatefulCall(b, n)
	default:
		return parser.NodeError(n, "this node is not supported in a view", "unsupported node type %T", n)
	}
	return nil
}

func (g *templateGen) writeFor(b *strings.Builder, n *parser.For) error {
	idx := g.eachN
	g.eachN++
	g.emitWrite(b, fmt.Sprintf("<!--g:each:%d:open-->", idx))
	switch {
	case n.Key != "" && n.Value != "":
		fmt.Fprintf(b, "\t\tfor %s, %s := range %s {\n", n.Key, n.Value, goExpr(n.X))
	case n.Key != "":
		fmt.Fprintf(b, "\t\tfor %s := range %s {\n", n.Key, goExpr(n.X))
	default:
		fmt.Fprintf(b, "\t\tfor range %s {\n", goExpr(n.X))
	}
	for _, child := range n.Children {
		if err := g.writeNode(b, child); err != nil {
			return err
		}
	}
	b.WriteString("\t\t}\n")
	g.emitWrite(b, fmt.Sprintf("<!--g:each:%d:close-->", idx))
	return nil
}

func (g *templateGen) writeIf(b *strings.Builder, n *parser.If) error {
	idx := g.ifN
	g.ifN++
	g.emitWrite(b, fmt.Sprintf("<!--g:if:%d:open-->", idx))
	fmt.Fprintf(b, "\t\tif %s {\n", goExpr(n.Cond))
	g.emitWrite(b, fmt.Sprintf("<!--g:if:%d:then-->", idx))
	for _, child := range n.Then {
		if err := g.writeNode(b, child); err != nil {
			return err
		}
	}
	b.WriteString("\t\t} else {\n")
	g.emitWrite(b, fmt.Sprintf("<!--g:if:%d:else-->", idx))
	for _, child := range n.Else {
		if err := g.writeNode(b, child); err != nil {
			return err
		}
	}
	b.WriteString("\t\t}\n")
	g.emitWrite(b, fmt.Sprintf("<!--g:if:%d:close-->", idx))
	return nil
}

func (g *templateGen) emitWrite(b *strings.Builder, s string) {
	fmt.Fprintf(b, "\t\tif err := write(%s); err != nil {\n\t\t\treturn err\n\t\t}\n", strconv.Quote(s))
}

func writeStatefulWrapper(b *strings.Builder, comp *Stateful) {
	propsSig := ""
	viewProps := ""
	if comp.PropsType != "" {
		propsSig = ", props " + comp.PropsGoType()
		viewProps = ", props"
	}
	fmt.Fprintf(b, "func %s(id string, key string%s) gothic.Component {\n", comp.GoName, propsSig)
	b.WriteString("\treturn gothic.ComponentFunc(func(ctx context.Context, w io.Writer) error {\n")
	fmt.Fprintf(b, "\t\tvar model %s\n", comp.ModelType)
	b.WriteString("\t\tstateJSON, err := json.Marshal(model)\n")
	b.WriteString("\t\tif err != nil {\n\t\t\treturn err\n\t\t}\n")
	fmt.Fprintf(b, "\t\tif _, err := io.WriteString(w, %s); err != nil {\n\t\t\treturn err\n\t\t}\n", strconv.Quote("<div data-gothic-component=\""+comp.Name+"\" data-gothic-component-id=\""))
	b.WriteString("\t\tif _, err := io.WriteString(w, id); err != nil {\n\t\t\treturn err\n\t\t}\n")
	b.WriteString("\t\tif _, err := io.WriteString(w, \"\\\"\"); err != nil {\n\t\t\treturn err\n\t\t}\n")
	b.WriteString("\t\tif key != \"\" {\n")
	b.WriteString("\t\t\tif _, err := io.WriteString(w, \" data-gothic-key=\\\"\"); err != nil {\n\t\t\t\treturn err\n\t\t\t}\n")
	b.WriteString("\t\t\tif _, err := io.WriteString(w, html.EscapeString(key)); err != nil {\n\t\t\t\treturn err\n\t\t\t}\n")
	b.WriteString("\t\t\tif _, err := io.WriteString(w, \"\\\"\"); err != nil {\n\t\t\t\treturn err\n\t\t\t}\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t\tif _, err := io.WriteString(w, \">\"); err != nil {\n\t\t\treturn err\n\t\t}\n")
	b.WriteString("\t\tif _, err := io.WriteString(w, \"<script type=\\\"application/json\\\" data-gothic-component-state>\"); err != nil {\n\t\t\treturn err\n\t\t}\n")
	b.WriteString("\t\tif _, err := w.Write(stateJSON); err != nil {\n\t\t\treturn err\n\t\t}\n")
	b.WriteString("\t\tif _, err := io.WriteString(w, \"</script>\"); err != nil {\n\t\t\treturn err\n\t\t}\n")
	fmt.Fprintf(b, "\t\tif err := %s(model%s).Render(ctx, w); err != nil {\n\t\t\treturn err\n\t\t}\n", comp.ViewName, viewProps)
	b.WriteString("\t\t_, err = io.WriteString(w, \"</div>\")\n\t\treturn err\n\t})\n}\n\n")
}

func matchPropField(fields []parser.Param, tag string) (parser.Param, bool, error) {
	var match parser.Param
	found := 0
	for _, f := range fields {
		if strings.EqualFold(f.Name, tag) {
			match = f
			found++
		}
	}
	if found > 1 {
		return parser.Param{}, false, fmt.Errorf("ambiguous prop %q", tag)
	}
	return match, found == 1, nil
}

func (g *templateGen) goPropsLiteral(comp *Stateful, call *parser.ComponentCall) (string, error) {
	if comp.PropsType == "" {
		if len(call.Props) > 0 {
			return "", parser.NodeError(call, "check the component signature", "component %s does not accept props", call.Name)
		}
		return "", nil
	}
	used := map[string]bool{}
	parts := make([]string, 0, len(comp.Props))
	for _, prop := range call.Props {
		field, ok, err := matchPropField(comp.Props, prop.Name)
		if err != nil {
			return "", parser.NodeError(call, "rename the prop field to avoid ambiguity", "component %s: %v", call.Name, err)
		}
		if !ok {
			return "", parser.NodeError(call, "check the props struct fields", "component %s: unknown prop %q", call.Name, prop.Name)
		}
		if used[field.Name] {
			return "", parser.NodeError(call, "remove the duplicate prop", "component %s: duplicate prop %q", call.Name, prop.Name)
		}
		used[field.Name] = true
		parts = append(parts, field.Name+": "+goExpr(prop.Value))
	}
	for _, field := range comp.Props {
		if !used[field.Name] {
			if strings.HasPrefix(field.Type, "*") {
				continue
			}
			return "", parser.NodeError(call, "provide all props, or make the field a pointer for optional props", "component %s: missing prop %q", call.Name, field.Name)
		}
	}
	return comp.PropsGoType() + "{" + strings.Join(parts, ", ") + "}", nil
}

func (g *templateGen) writeStatefulCall(b *strings.Builder, call *parser.ComponentCall) error {
	if !g.allowStateful {
		return parser.NodeError(call, "move the component to the App view", "stateful component %s cannot be nested inside another stateful component yet", call.Name)
	}
	comp := g.stateful[call.Name]
	if comp == nil {
		return parser.NodeError(call, "add a //gothic:components directive for the component package", "unknown stateful component %s", call.Name)
	}
	id := fmt.Sprintf("c%d", g.componentN)
	g.componentN++
	args := []string{strconv.Quote(id)}
	if call.Key != nil {
		g.usesFmt = true
		args = append(args, "fmt.Sprint("+goExpr(call.Key)+")")
	} else {
		args = append(args, `""`)
	}
	props, err := g.goPropsLiteral(comp, call)
	if err != nil {
		return err
	}
	if comp.PropsType != "" {
		args = append(args, props)
	}
	callee := comp.GoName
	if comp.External {
		callee = comp.ImportAlias + "." + comp.GoName
	}
	fmt.Fprintf(b, "\t\tif err := %s(%s).Render(ctx, w); err != nil {\n\t\t\treturn err\n\t\t}\n", callee, strings.Join(args, ", "))
	return nil
}

func writeRegistrar(b *strings.Builder, f *parser.File) {
	iface := f.Templates[0].Name + "Procedures"
	fmt.Fprintf(b, "// %s is implemented by the application to serve this file's procedures.\n", iface)
	fmt.Fprintf(b, "type %s interface {\n", iface)
	for _, p := range f.Procedures {
		fmt.Fprintf(b, "\t%s(ctx context.Context) (%s, error)\n", p.Name, p.ResultType)
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(b, "// Register%s mounts this file's procedures on s.\n", f.Templates[0].Name)
	fmt.Fprintf(b, "func Register%s(s *gothic.Server, impl %s) {\n", f.Templates[0].Name, iface)
	for _, p := range f.Procedures {
		fmt.Fprintf(b, "\ts.RegisterProcedure(%s, func(ctx context.Context, body []byte) (any, error) {\n", strconv.Quote(p.Name))
		fmt.Fprintf(b, "\t\treturn impl.%s(ctx)\n", p.Name)
		b.WriteString("\t})\n")
	}
	b.WriteString("}\n")

	for _, p := range f.Procedures {
		fmt.Fprintf(b, "\n// %s is the client-side stub for the %s procedure.\n", p.Name, p.Name)
		fmt.Fprintf(b, "func %s() (%s, error) {\n", p.Name, p.ResultType)
		fmt.Fprintf(b, "\tpanic(%s)\n", strconv.Quote("gothic: "+p.Name+" is a client-only procedure"))
		b.WriteString("}\n")
	}
}

func writeAppRegistrar(b *strings.Builder, app *goapp.App) {
	iface := app.ProceduresType
	fmt.Fprintf(b, "// Register%s mounts the declared procedures on s.\n", iface)
	fmt.Fprintf(b, "func Register%s(s *gothic.Server, impl %s) {\n", iface, iface)
	for _, p := range app.Procedures {
		fmt.Fprintf(b, "\ts.RegisterProcedure(%s, func(ctx context.Context, body []byte) (any, error) {\n", strconv.Quote(p.Name))
		if len(p.Params) > 0 {
			refs := make([]string, len(p.Params))
			for i, param := range p.Params {
				name := fmt.Sprintf("arg%d", i)
				fmt.Fprintf(b, "\t\tvar %s %s\n", name, param.Type)
				refs[i] = "&" + name
			}
			fmt.Fprintf(b, "\t\tif err := gothic.UnmarshalArgs(body, %s); err != nil {\n\t\t\treturn nil, err\n\t\t}\n", strings.Join(refs, ", "))
		}
		args := []string{"ctx"}
		for i := range p.Params {
			args = append(args, fmt.Sprintf("arg%d", i))
		}
		if p.ResultType == "" {
			fmt.Fprintf(b, "\t\tif err := impl.%s(%s); err != nil {\n\t\t\treturn nil, err\n\t\t}\n", p.Name, strings.Join(args, ", "))
			b.WriteString("\t\treturn nil, nil\n")
		} else {
			fmt.Fprintf(b, "\t\treturn impl.%s(%s)\n", p.Name, strings.Join(args, ", "))
		}
		b.WriteString("\t})\n")
	}
	b.WriteString("}\n")

	for _, p := range app.Procedures {
		fmt.Fprintf(b, "\n// %s is the client-side stub for the %s procedure.\n", p.Name, p.Name)
		sig := procedureParamsSig(p)
		if p.ResultType == "" {
			fmt.Fprintf(b, "func %s(%s) error {\n", p.Name, sig)
		} else {
			fmt.Fprintf(b, "func %s(%s) (%s, error) {\n", p.Name, sig, p.ResultType)
		}
		fmt.Fprintf(b, "\tpanic(%s)\n", strconv.Quote("gothic: "+p.Name+" is a client-only procedure"))
		b.WriteString("}\n")
	}
}

func procedureParamsSig(p goapp.Procedure) string {
	parts := make([]string, len(p.Params))
	for i, param := range p.Params {
		parts[i] = param.Name + " " + param.Type
	}
	return strings.Join(parts, ", ")
}

func paramsOrEmpty(t *parser.Template) string {
	if strings.TrimSpace(t.Params) == "" {
		return "()"
	}
	return t.Params
}

func goExpr(e ast.Expr) string {
	var b bytes.Buffer
	_ = format.Node(&b, token.NewFileSet(), e)
	return b.String()
}

func goStateMap(state []parser.StateDecl) string {
	if len(state) == 0 {
		return "map[string]any{}"
	}
	decls := append([]parser.StateDecl(nil), state...)
	sort.Slice(decls, func(i, j int) bool { return decls[i].Name < decls[j].Name })
	parts := make([]string, len(decls))
	for i, sd := range decls {
		parts[i] = strconv.Quote(sd.Name) + ": " + sd.Name
	}
	return "map[string]any{" + strings.Join(parts, ", ") + "}"
}

func sanitizeIdent(s string) string {
	var b strings.Builder
	for i, r := range s {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r == '_') || (i > 0 && r >= '0' && r <= '9') {
			b.WriteRune(r)
		} else {
			b.WriteRune('_')
		}
	}
	return b.String()
}

func statefulMap(components []*Stateful) map[string]*Stateful {
	m := make(map[string]*Stateful, len(components))
	for _, c := range components {
		m[c.Name] = c
	}
	return m
}

// LibraryOptions controls a precompiled component library output.
type LibraryOptions struct {
	FileName   string
	Package    string
	ModuleFile string
	ModuleURL  string
	Preludes   [][]byte
	Stateful   []*Stateful
}

// GenerateLibrary renders a Go package containing precompiled stateful components.
func GenerateLibrary(opts LibraryOptions) ([]byte, error) {
	var preludeImports []importSpec
	var decls strings.Builder
	pkg := opts.Package
	for _, prelude := range opts.Preludes {
		fset := token.NewFileSet()
		file, err := goparser.ParseFile(fset, opts.FileName, prelude, goparser.ParseComments)
		if err != nil {
			return nil, fmt.Errorf("%s: parsing prelude: %w", opts.FileName, err)
		}
		if pkg == "" {
			pkg = file.Name.Name
		}
		for _, imp := range file.Imports {
			name := ""
			if imp.Name != nil {
				name = imp.Name.Name
			}
			preludeImports = append(preludeImports, importSpec{Name: name, Path: imp.Path.Value})
		}
		var start token.Pos
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if ok && gen.Tok == token.IMPORT {
				start = gen.End()
			}
		}
		if start == token.NoPos {
			start = file.Name.End()
		}
		offset := fset.Position(start).Offset
		if offset < 0 || offset > len(prelude) {
			return nil, fmt.Errorf("%s: invalid prelude offset", opts.FileName)
		}
		part := prelude[offset:]
		decls.Write(part)
		if len(part) == 0 || part[len(part)-1] != '\n' {
			decls.WriteString("\n")
		}
	}

	var body strings.Builder
	usesHTML := false
	usesFmt := false
	for _, comp := range opts.Stateful {
		viewGen := &templateGen{
			t:             comp.View,
			funcName:      comp.ViewName,
			appRoot:       false,
			allowStateful: false,
		}
		code, err := viewGen.generateComponentView()
		if err != nil {
			return nil, wrapFile(opts.FileName, err)
		}
		if viewGen.usesHTML {
			usesHTML = true
		}
		if viewGen.usesFmt {
			usesFmt = true
		}
		body.WriteString(code)
		body.WriteString("\n")
		writeStatefulWrapper(&body, comp)
		usesHTML = true
	}

	embedName := sanitizeIdent(opts.Package) + "ComponentsJS"
	if embedName == "ComponentsJS" {
		embedName = "LibraryComponentsJS"
	}
	body.WriteString("//go:embed " + opts.ModuleFile + "\n")
	body.WriteString("var " + embedName + " []byte\n\n")
	body.WriteString("func init() {\n")
	body.WriteString("\tgothic.RegisterModule(" + strconv.Quote(opts.ModuleURL) + ", " + embedName + ")\n")
	body.WriteString("}\n\n")

	imports, err := mergeImports(preludeImports, viewImports(usesHTML, usesFmt))
	if err != nil {
		return nil, wrapFile(opts.FileName, err)
	}

	var b strings.Builder
	b.WriteString("// Code generated by gothic. DO NOT EDIT.\n\n")
	b.WriteString("package " + pkg + "\n\n")
	writeImportBlock(&b, imports)
	b.WriteString(decls.String())
	if decls.Len() > 0 && !strings.HasSuffix(decls.String(), "\n") {
		b.WriteString("\n")
	}
	b.WriteString(body.String())
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("%s: formatting generated Go: %w", opts.FileName, err)
	}
	return formatted, nil
}
