// Package appjs emits a Bubble Tea-style gothic application module.
package appjs

import (
	"encoding/json"
	"fmt"
	"go/ast"
	"go/token"
	"strconv"
	"strings"

	"github.com/metruzanca/gothic/goapp"
	"github.com/metruzanca/gothic/parser"
)

// Options controls the generated module.
type Options struct {
	FileName   string
	RuntimeURL string
}

// Generate renders the JavaScript application module for the view and app.
func Generate(view *parser.File, app *goapp.App, opts Options) ([]byte, error) {
	if len(view.Templates) != 1 || view.Templates[0].Name != "App" {
		return nil, fmt.Errorf("%s: components must be expanded into a single App view", opts.FileName)
	}
	t := view.Templates[0]
	modelName, _, ok := singleModelParam(t.Params)
	if !ok {
		return nil, fmt.Errorf("%s: app view must have a single model parameter", opts.FileName)
	}
	if opts.RuntimeURL == "" {
		opts.RuntimeURL = "/_gothic/runtime.js"
	}
	g := &gen{
		t:         t,
		app:       app,
		rootID:    strings.ToLower(t.Name),
		modelName: modelName,
		varN:      0,
		tempN:     0,
		eachN:     0,
		eventN:    0,
	}

	var bindings strings.Builder
	if err := g.emitViewBindings(&bindings); err != nil {
		return nil, fmt.Errorf("%s: %w", opts.FileName, err)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gothic from %s. DO NOT EDIT.\n\n", baseName(opts.FileName))
	fmt.Fprintf(&b, "import { list, on, readState, rpc, text } from %s;\n\n", jsString(opts.RuntimeURL))
	for _, p := range app.Procedures {
		fmt.Fprintf(&b, "const %s = (...args) => rpc(%s, ...args);\n", p.Name, jsString(p.Name))
	}
	if len(app.Procedures) > 0 {
		b.WriteString("\n")
	}
	fmt.Fprintf(&b, "const root = document.querySelector('[data-gothic-root=%s]');\n", jsString(g.rootID))
	fmt.Fprintf(&b, "let model = readState(%s);\n\n", jsString(g.rootID))
	b.WriteString(bindings.String())
	b.WriteString("\n")
	g.emitRender(&b)
	g.emitDispatch(&b)

	if err := g.emitInit(&b); err != nil {
		return nil, fmt.Errorf("%s: %w", opts.FileName, err)
	}
	if err := g.emitUpdate(&b); err != nil {
		return nil, fmt.Errorf("%s: %w", opts.FileName, err)
	}
	for name := range app.ReferencedCommands {
		fn := app.Commands[name]
		if fn == nil {
			continue
		}
		if err := g.emitCommand(&b, fn); err != nil {
			return nil, fmt.Errorf("%s: %w", opts.FileName, err)
		}
	}

	b.WriteString("render(model);\nrun(init());\n")
	return []byte(b.String()), nil
}

type gen struct {
	t         *parser.Template
	app       *goapp.App
	rootID    string
	modelName string
	varN      int
	tempN     int
	eachN     int
	eventN    int
	textN     int
	listCalls []string
	textCalls []string
}

type itemBinding struct {
	kind   string
	marker int
	event  string
	expr   string
}

func (g *gen) emitViewBindings(b *strings.Builder) error {
	if len(g.t.Children) != 1 {
		return fmt.Errorf("view must have one root element")
	}
	root, ok := g.t.Children[0].(*parser.Element)
	if !ok {
		return fmt.Errorf("view root must be an element")
	}
	return g.emitElementBindings(b, root)
}

func (g *gen) emitElementBindings(b *strings.Builder, el *parser.Element) error {
	for _, attr := range el.Attributes {
		ev, ok := attr.(*parser.EventAttr)
		if !ok {
			continue
		}
		idx := g.eventN
		g.eventN++
		msg, err := g.expr(ev.Expr, exprCtx{})
		if err != nil {
			return err
		}
		event := strings.TrimPrefix(ev.Name, "on")
		fmt.Fprintf(b, "on(root, %s, %s, () => dispatch(%s));\n", jsString(fmt.Sprintf("%d", idx)), jsString(event), msg)
	}
	for _, child := range el.Children {
		switch c := child.(type) {
		case *parser.Element:
			if err := g.emitElementBindings(b, c); err != nil {
				return err
			}
		case *parser.Interpolation:
			idx := g.textN
			g.textN++
			expr, err := g.expr(c.Expr, exprCtx{})
			if err != nil {
				return err
			}
			g.textCalls = append(g.textCalls, fmt.Sprintf("text(root, %s, %s);", jsString(fmt.Sprintf("%d", idx)), expr))
		case *parser.For:
			if err := g.emitForBinding(b, c); err != nil {
				return err
			}
		}
	}
	return nil
}

func (g *gen) emitForBinding(b *strings.Builder, f *parser.For) error {
	if f.Value == "" {
		return fmt.Errorf("for loops must use _, value := range expr")
	}
	idx := g.eachN
	g.eachN++
	renderName := fmt.Sprintf("renderList%d", idx)

	var item strings.Builder
	var bindings []itemBinding
	g.varN = 0
	var rootVar string
	for _, child := range f.Children {
		el, ok := child.(*parser.Element)
		if !ok {
			continue
		}
		var err error
		rootVar, err = g.emitDOM(&item, el, map[string]bool{f.Value: true}, &bindings)
		if err != nil {
			return err
		}
	}
	if rootVar == "" {
		return fmt.Errorf("for body must contain one element")
	}

	fmt.Fprintf(b, "const %s = list(root, %s, (%s) => {\n", renderName, jsString(fmt.Sprintf("%d", idx)), f.Value)
	b.WriteString(item.String())
	emitItemBindings(b, rootVar, bindings)
	fmt.Fprintf(b, "  return %s;\n}", rootVar)
	if len(bindings) > 0 {
		fmt.Fprintf(b, ", (node, %s) => {\n", f.Value)
		emitItemBindings(b, "node", bindings)
		b.WriteString("});\n")
	} else {
		b.WriteString(");\n")
	}

	itemsExpr, err := g.expr(f.X, exprCtx{})
	if err != nil {
		return err
	}
	g.listCalls = append(g.listCalls, fmt.Sprintf("%s(%s);", renderName, itemsExpr))
	return nil
}

func emitItemBindings(b *strings.Builder, root string, bindings []itemBinding) {
	for _, binding := range bindings {
		switch binding.kind {
		case "text":
			fmt.Fprintf(b, "  text(%s, %s, %s);\n", root, jsString(fmt.Sprintf("%d", binding.marker)), binding.expr)
		case "event":
			fmt.Fprintf(b, "  on(%s, %s, %s, () => dispatch(%s));\n", root, jsString(fmt.Sprintf("%d", binding.marker)), jsString(binding.event), binding.expr)
		}
	}
}

func (g *gen) emitDOM(sb *strings.Builder, el *parser.Element, locals map[string]bool, bindings *[]itemBinding) (string, error) {
	v := fmt.Sprintf("e%d", g.varN)
	g.varN++
	fmt.Fprintf(sb, "  const %s = document.createElement(%s);\n", v, jsString(el.Name))
	for _, attr := range el.Attributes {
		switch a := attr.(type) {
		case *parser.ConstantAttr:
			if a.Value != "" {
				fmt.Fprintf(sb, "  %s.setAttribute(%s, %s);\n", v, jsString(a.Name), jsString(a.Value))
			}
		case *parser.EventAttr:
			idx := g.eventN
			g.eventN++
			msg, err := g.expr(a.Expr, exprCtx{locals: locals})
			if err != nil {
				return "", err
			}
			fmt.Fprintf(sb, "  %s.setAttribute(\"data-gothic-on\", %s);\n", v, jsString(fmt.Sprintf("%d", idx)))
			*bindings = append(*bindings, itemBinding{
				kind:   "event",
				marker: idx,
				event:  strings.TrimPrefix(a.Name, "on"),
				expr:   msg,
			})
		}
	}
	for _, child := range el.Children {
		switch c := child.(type) {
		case *parser.Text:
			fmt.Fprintf(sb, "  %s.appendChild(document.createTextNode(%s));\n", v, jsString(c.Value))
		case *parser.Interpolation:
			idx := g.textN
			g.textN++
			e, err := g.expr(c.Expr, exprCtx{locals: locals})
			if err != nil {
				return "", err
			}
			fmt.Fprintf(sb, "  %s.appendChild(document.createTextNode(String(%s)));\n", v, e)
			*bindings = append(*bindings, itemBinding{kind: "text", marker: idx, expr: e})
		case *parser.Element:
			childVar, err := g.emitDOM(sb, c, locals, bindings)
			if err != nil {
				return "", err
			}
			fmt.Fprintf(sb, "  %s.appendChild(%s);\n", v, childVar)
		case *parser.For:
			return "", fmt.Errorf("nested for is not supported yet")
		}
	}
	return v, nil
}

func (g *gen) emitRender(b *strings.Builder) {
	b.WriteString("function render(model) {\n")
	for _, call := range g.textCalls {
		fmt.Fprintf(b, "  %s\n", call)
	}
	for _, call := range g.listCalls {
		fmt.Fprintf(b, "  %s\n", call)
	}
	b.WriteString("}\n\n")
}

func (g *gen) emitDispatch(b *strings.Builder) {
	b.WriteString(`function dispatch(msg) {
  const result = update(model, msg);
  model = result[0];
  render(model);
  if (result[1]) run(result[1]);
}

async function run(cmd) {
  if (!cmd) return;
  const msg = await cmd();
  if (msg) dispatch(msg);
}

`)
}

func (g *gen) emitInit(b *strings.Builder) error {
	b.WriteString("function init() {\n")
	if g.app.Init != nil {
		ctx := &exprCtx{}
		for _, st := range g.app.Init.Body.List {
			if err := g.stmt(b, st, ctx, 1); err != nil {
				return err
			}
		}
	}
	b.WriteString("}\n\n")
	return nil
}

func (g *gen) emitUpdate(b *strings.Builder) error {
	b.WriteString("function update(m, msg) {\n")
	ctx := &exprCtx{inUpdate: true}
	for _, st := range g.app.Update.Body.List {
		if err := g.stmt(b, st, ctx, 1); err != nil {
			return err
		}
	}
	b.WriteString("}\n\n")
	return nil
}

func (g *gen) emitCommand(b *strings.Builder, fn *ast.FuncDecl) error {
	if fn.Type.Params != nil && len(fn.Type.Params.List) != 0 {
		return fmt.Errorf("commands with parameters are not supported yet")
	}
	fmt.Fprintf(b, "async function %s() {\n", fn.Name.Name)
	ctx := &exprCtx{async: true}
	for _, st := range fn.Body.List {
		if err := g.stmt(b, st, ctx, 1); err != nil {
			return err
		}
	}
	b.WriteString("}\n\n")
	return nil
}

type exprCtx struct {
	locals   map[string]bool
	async    bool
	inUpdate bool
}

func (g *gen) stmt(b *strings.Builder, s ast.Stmt, ctx *exprCtx, indent int) error {
	pad := strings.Repeat("  ", indent)
	switch s := s.(type) {
	case *ast.AssignStmt:
		return g.assign(b, s, ctx, pad)
	case *ast.IfStmt:
		cond, err := g.expr(s.Cond, *ctx)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%sif (%s) {\n", pad, cond)
		for _, st := range s.Body.List {
			if err := g.stmt(b, st, ctx, indent+1); err != nil {
				return err
			}
		}
		fmt.Fprintf(b, "%s}", pad)
		if block, ok := s.Else.(*ast.BlockStmt); ok {
			b.WriteString(" else {\n")
			for _, st := range block.List {
				if err := g.stmt(b, st, ctx, indent+1); err != nil {
					return err
				}
			}
			fmt.Fprintf(b, "%s}", pad)
		}
		b.WriteString("\n")
		return nil
	case *ast.ReturnStmt:
		if ctx.inUpdate {
			if len(s.Results) != 2 {
				return fmt.Errorf("Update must return (model, cmd)")
			}
			a, err := g.expr(s.Results[0], *ctx)
			if err != nil {
				return err
			}
			c, err := g.expr(s.Results[1], *ctx)
			if err != nil {
				return err
			}
			fmt.Fprintf(b, "%sreturn [%s, %s];\n", pad, a, c)
			return nil
		}
		if len(s.Results) == 0 {
			fmt.Fprintf(b, "%sreturn;\n", pad)
			return nil
		}
		if len(s.Results) != 1 {
			return fmt.Errorf("unsupported return")
		}
		e, err := g.expr(s.Results[0], *ctx)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%sreturn %s;\n", pad, e)
		return nil
	case *ast.TypeSwitchStmt:
		return g.typeSwitch(b, s, ctx, indent)
	case *ast.ExprStmt:
		e, err := g.expr(s.X, *ctx)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%s%s;\n", pad, e)
		return nil
	case *ast.BlockStmt:
		for _, st := range s.List {
			if err := g.stmt(b, st, ctx, indent); err != nil {
				return err
			}
		}
		return nil
	case *ast.EmptyStmt:
		return nil
	default:
		return fmt.Errorf("unsupported statement %T", s)
	}
}

func (g *gen) assign(b *strings.Builder, s *ast.AssignStmt, ctx *exprCtx, pad string) error {
	if len(s.Lhs) == 2 && len(s.Rhs) == 1 && s.Tok == token.DEFINE {
		call, ok := s.Rhs[0].(*ast.CallExpr)
		if !ok {
			return fmt.Errorf("two-value assignment requires a call")
		}
		a, ok := identName(s.Lhs[0])
		if !ok {
			return fmt.Errorf("two-value assignment requires identifiers")
		}
		errName, ok := identName(s.Lhs[1])
		if !ok {
			return fmt.Errorf("two-value assignment requires identifiers")
		}
		callExpr, err := g.expr(call, *ctx)
		if err != nil {
			return err
		}
		tmp := g.temp()
		fmt.Fprintf(b, "%slet %s, %s;\n", pad, a, errName)
		fmt.Fprintf(b, "%stry {\n", pad)
		fmt.Fprintf(b, "%s  %s = %s;\n", pad, a, callExpr)
		fmt.Fprintf(b, "%s} catch (%s) {\n", pad, tmp)
		fmt.Fprintf(b, "%s  %s = %s;\n", pad, errName, tmp)
		fmt.Fprintf(b, "%s}\n", pad)
		return nil
	}
	if len(s.Lhs) != 1 || len(s.Rhs) != 1 {
		return fmt.Errorf("unsupported assignment")
	}
	lhs, rhs := s.Lhs[0], s.Rhs[0]
	if call, ok := rhs.(*ast.CallExpr); ok && isAppend(call) {
		lhsExpr, err := g.expr(lhs, *ctx)
		if err != nil {
			return err
		}
		args := make([]string, 0, len(call.Args)-1)
		for _, a := range call.Args[1:] {
			e, err := g.expr(a, *ctx)
			if err != nil {
				return err
			}
			args = append(args, e)
		}
		fmt.Fprintf(b, "%s%s.push(%s);\n", pad, lhsExpr, strings.Join(args, ", "))
		return nil
	}
	lhsExpr, err := g.expr(lhs, *ctx)
	if err != nil {
		return err
	}
	rhsExpr, err := g.expr(rhs, *ctx)
	if err != nil {
		return err
	}
	if s.Tok == token.DEFINE {
		fmt.Fprintf(b, "%sconst %s = %s;\n", pad, lhsExpr, rhsExpr)
		return nil
	}
	fmt.Fprintf(b, "%s%s = %s;\n", pad, lhsExpr, rhsExpr)
	return nil
}

func (g *gen) typeSwitch(b *strings.Builder, s *ast.TypeSwitchStmt, ctx *exprCtx, indent int) error {
	assign, ok := s.Assign.(*ast.AssignStmt)
	if !ok || len(assign.Lhs) != 1 {
		return fmt.Errorf("unsupported type switch")
	}
	tag, ok := identName(assign.Lhs[0])
	if !ok {
		return fmt.Errorf("unsupported type switch tag")
	}
	pad := strings.Repeat("  ", indent)
	fmt.Fprintf(b, "%sswitch (%s.tag) {\n", pad, tag)
	for _, stmt := range s.Body.List {
		cc, ok := stmt.(*ast.CaseClause)
		if !ok {
			return fmt.Errorf("unsupported type switch case")
		}
		if cc.List == nil {
			fmt.Fprintf(b, "%sdefault:\n", pad)
		}
		for _, e := range cc.List {
			id, ok := e.(*ast.Ident)
			if !ok {
				return fmt.Errorf("unsupported type switch case type")
			}
			fmt.Fprintf(b, "%scase %s:\n", pad, jsString(id.Name))
		}
		for _, st := range cc.Body {
			if err := g.stmt(b, st, ctx, indent+1); err != nil {
				return err
			}
		}
		fmt.Fprintf(b, "%s  break;\n", pad)
	}
	fmt.Fprintf(b, "%s}\n", pad)
	return nil
}

func (g *gen) expr(e ast.Expr, ctx exprCtx) (string, error) {
	switch e := e.(type) {
	case *ast.Ident:
		if ctx.locals[e.Name] {
			return e.Name, nil
		}
		if e.Name == "nil" {
			return "null", nil
		}
		return e.Name, nil
	case *ast.BasicLit:
		switch e.Kind {
		case token.STRING:
			v, err := strconv.Unquote(e.Value)
			if err != nil {
				return "", err
			}
			return jsString(v), nil
		case token.INT, token.FLOAT:
			return e.Value, nil
		case token.CHAR:
			v, err := strconv.Unquote(e.Value)
			if err != nil {
				return "", err
			}
			return jsString(v), nil
		default:
			return "", fmt.Errorf("unsupported literal %s", e.Value)
		}
	case *ast.SelectorExpr:
		if e.Sel.Name == "Error" {
			x, err := g.expr(e.X, ctx)
			if err != nil {
				return "", err
			}
			return x + ".message", nil
		}
		x, err := g.expr(e.X, ctx)
		if err != nil {
			return "", err
		}
		return x + "." + e.Sel.Name, nil
	case *ast.CallExpr:
		if id, ok := e.Fun.(*ast.Ident); ok && id.Name == "append" {
			return "", fmt.Errorf("append is only supported in assignment")
		}
		if sel, ok := e.Fun.(*ast.SelectorExpr); ok && sel.Sel.Name == "Error" {
			x, err := g.expr(sel.X, ctx)
			if err != nil {
				return "", err
			}
			return x + ".message", nil
		}
		fun, err := g.expr(e.Fun, ctx)
		if err != nil {
			return "", err
		}
		args := make([]string, 0, len(e.Args))
		for _, a := range e.Args {
			v, err := g.expr(a, ctx)
			if err != nil {
				return "", err
			}
			args = append(args, v)
		}
		call := fmt.Sprintf("%s(%s)", fun, strings.Join(args, ", "))
		if ctx.async {
			return "await " + call, nil
		}
		return call, nil
	case *ast.BinaryExpr:
		x, err := g.expr(e.X, ctx)
		if err != nil {
			return "", err
		}
		y, err := g.expr(e.Y, ctx)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("%s %s %s", x, e.Op.String(), y), nil
	case *ast.UnaryExpr:
		x, err := g.expr(e.X, ctx)
		if err != nil {
			return "", err
		}
		return e.Op.String() + x, nil
	case *ast.ParenExpr:
		x, err := g.expr(e.X, ctx)
		if err != nil {
			return "", err
		}
		return "(" + x + ")", nil
	case *ast.CompositeLit:
		return g.composite(e, ctx)
	default:
		return "", fmt.Errorf("unsupported expression %T", e)
	}
}

func (g *gen) composite(e *ast.CompositeLit, ctx exprCtx) (string, error) {
	switch t := e.Type.(type) {
	case *ast.Ident:
		if _, ok := g.app.Messages[t.Name]; !ok {
			return "", fmt.Errorf("unknown message type %s", t.Name)
		}
		parts := []string{fmt.Sprintf("tag: %s", jsString(t.Name))}
		for _, elt := range e.Elts {
			kv, ok := elt.(*ast.KeyValueExpr)
			if !ok {
				return "", fmt.Errorf("message literals must use keyed fields")
			}
			key, ok := identName(kv.Key)
			if !ok {
				return "", fmt.Errorf("message fields must be identifiers")
			}
			val, err := g.expr(kv.Value, ctx)
			if err != nil {
				return "", err
			}
			parts = append(parts, key+": "+val)
		}
		return "{" + strings.Join(parts, ", ") + "}", nil
	case *ast.ArrayType:
		parts := make([]string, 0, len(e.Elts))
		for _, elt := range e.Elts {
			v, err := g.expr(elt, ctx)
			if err != nil {
				return "", err
			}
			parts = append(parts, v)
		}
		return "[" + strings.Join(parts, ", ") + "]", nil
	default:
		return "", fmt.Errorf("unsupported composite literal %T", e.Type)
	}
}

func (g *gen) temp() string {
	g.tempN++
	return fmt.Sprintf("__gothicErr%d", g.tempN)
}

func identName(e ast.Expr) (string, bool) {
	id, ok := e.(*ast.Ident)
	if !ok {
		return "", false
	}
	return id.Name, true
}

func isAppend(c *ast.CallExpr) bool {
	id, ok := c.Fun.(*ast.Ident)
	return ok && id.Name == "append" && len(c.Args) >= 2
}

func singleModelParam(params string) (name, typ string, ok bool) {
	p := strings.TrimSpace(params)
	p = strings.TrimPrefix(p, "(")
	p = strings.TrimSuffix(p, ")")
	p = strings.TrimSpace(p)
	if p == "" || strings.Contains(p, ",") {
		return "", "", false
	}
	parts := strings.Fields(p)
	if len(parts) != 2 {
		return "", "", false
	}
	return parts[0], parts[1], true
}

func jsString(s string) string {
	b, err := json.Marshal(s)
	if err != nil {
		return `""`
	}
	return string(b)
}

func baseName(path string) string {
	if i := strings.LastIndexAny(path, `/\`); i >= 0 {
		return path[i+1:]
	}
	return path
}
