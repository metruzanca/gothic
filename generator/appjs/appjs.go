func (g *gen) stmt(b *strings.Builder, s ast.Stmt, ctx *exprCtx, indent int) error {
	ctx.pos = g.appPos(s.Pos())
	pad := strings.Repeat("  ", indent)
	switch s := s.(type) {
	case *ast.AssignStmt:
		return g.assign(b, s, ctx, pad)
	case *ast.IfStmt:
		cond, err := g.expr(s.Cond, *ctx)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%sif (%s) {\n", pad, cond)
		for _, st := range s.Body.List {
			if err := g.stmt(b, st, ctx, indent+1); err != nil {
				return err
			}
		}
		fmt.Fprintf(b, "%s}", pad)
		if block, ok := s.Else.(*ast.BlockStmt); ok {
			b.WriteString(" else {\n")
			for _, st := range block.List {
				if err := g.stmt(b, st, ctx, indent+1); err != nil {
					return err
				}
			}
			fmt.Fprintf(b, "%s}", pad)
		}
		b.WriteString("\n")
		return nil
	case *ast.ReturnStmt:
		if ctx.inUpdate {
			if len(s.Results) != 2 {
				return fmt.Errorf("Update must return (model, cmd)")
			}
			a, err := g.expr(s.Results[0], *ctx)
			if err != nil {
				return err
			}
			c, err := g.expr(s.Results[1], *ctx)
			if err != nil {
				return err
			}
			fmt.Fprintf(b, "%sreturn [%s, %s];\n", pad, a, c)
			return nil
		}
		if len(s.Results) == 0 {
			fmt.Fprintf(b, "%sreturn;\n", pad)
			return nil
		}
		if len(s.Results) != 1 {
			return fmt.Errorf("unsupported return")
		}
		e, err := g.expr(s.Results[0], *ctx)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%sreturn %s;\n", pad, e)
		return nil
	case *ast.TypeSwitchStmt:
		return g.typeSwitch(b, s, ctx, indent)
	case *ast.ExprStmt:
		e, err := g.expr(s.X, *ctx)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "%s%s;\n", pad, e)
		return nil
	case *ast.BlockStmt:
		for _, st := range s.List {
			if err := g.stmt(b, st, ctx, indent); err != nil {
				return err
			}
		}
		return nil
	case *ast.EmptyStmt:
		return nil
	default:
		return parser.PosError(ctx.pos, "this statement is not supported in the client subset", "unsupported statement %s", goStmtText(s))
	}
}

func (g *gen) assign(b *strings.Builder, s *ast.AssignStmt, ctx *exprCtx, pad string) error {
	if len(s.Lhs) == 2 && len(s.Rhs) == 1 && s.Tok == token.DEFINE {
		call, ok := s.Rhs[0].(*ast.CallExpr)
		if !ok {
			return fmt.Errorf("two-value assignment requires a call")
		}
		a, ok := identName(s.Lhs[0])
		if !ok {
			return fmt.Errorf("two-value assignment requires identifiers")
		}
		errName, ok := identName(s.Lhs[1])
		if !ok {
			return fmt.Errorf("two-value assignment requires identifiers")
		}
		callExpr, err := g.expr(call, *ctx)
		if err != nil {
			return err
		}
		tmp := g.temp()
		fmt.Fprintf(b, "%slet %s, %s;\n", pad, a, errName)
		fmt.Fprintf(b, "%stry {\n", pad)
		fmt.Fprintf(b, "%s  %s = %s;\n", pad, a, callExpr)
		fmt.Fprintf(b, "%s} catch (%s) {\n", pad, tmp)
		fmt.Fprintf(b, "%s  %s = %s;\n", pad, errName, tmp)
		fmt.Fprintf(b, "%s}\n", pad)
		return nil
	}
	if len(s.Lhs) != 1 || len(s.Rhs) != 1 {
		return fmt.Errorf("unsupported assignment")
	}
	lhs, rhs := s.Lhs[0], s.Rhs[0]
	if call, ok := rhs.(*ast.CallExpr); ok && g.isErrorProcedure(call) {
		if !ctx.async {
			return fmt.Errorf("procedures can only be called from commands")
		}
		lhsExpr, err := g.expr(lhs, *ctx)
		if err != nil {
			return err
		}
		callExpr, err := g.expr(call, *ctx)
		if err != nil {
			return err
		}
		tmp := g.temp()
		if s.Tok == token.DEFINE {
			fmt.Fprintf(b, "%slet %s = null;\n", pad, lhsExpr)
		} else {
			fmt.Fprintf(b, "%s%s = null;\n", pad, lhsExpr)
		}
		fmt.Fprintf(b, "%stry {\n", pad)
		fmt.Fprintf(b, "%s  %s = %s;\n", pad, lhsExpr, callExpr)
		fmt.Fprintf(b, "%s} catch (%s) {\n", pad, tmp)
		fmt.Fprintf(b, "%s  %s = %s;\n", pad, lhsExpr, tmp)
		fmt.Fprintf(b, "%s}\n", pad)
		return nil
	}
	if call, ok := rhs.(*ast.CallExpr); ok && isAppend(call) {
		lhsExpr, err := g.expr(lhs, *ctx)
		if err != nil {
			return err
		}
		args := make([]string, 0, len(call.Args)-1)
		for _, a := range call.Args[1:] {
			e, err := g.expr(a, *ctx)
			if err != nil {
				return err
			}
			args = append(args, e)
		}
		fmt.Fprintf(b, "%s(%s = %s || []).push(%s);\n", pad, lhsExpr, lhsExpr, strings.Join(args, ", "))
		return nil
	}
	lhsExpr, err := g.expr(lhs, *ctx)
	if err != nil {
		return err
	}
	rhsExpr, err := g.expr(rhs, *ctx)
	if err != nil {
		return err
	}
	if s.Tok == token.DEFINE {
		fmt.Fprintf(b, "%sconst %s = %s;\n", pad, lhsExpr, rhsExpr)
		return nil
	}
	fmt.Fprintf(b, "%s%s = %s;\n", pad, lhsExpr, rhsExpr)
	return nil
}

func (g *gen) typeSwitch(b *strings.Builder, s *ast.TypeSwitchStmt, ctx *exprCtx, indent int) error {
	var tag string
	switch assign := s.Assign.(type) {
	case *ast.AssignStmt:
		if len(assign.Lhs) != 1 {
			return fmt.Errorf("unsupported type switch")
		}
		name, ok := identName(assign.Lhs[0])
		if !ok {
			return fmt.Errorf("unsupported type switch tag")
		}
		tag = name
	case *ast.ExprStmt:
		assert, ok := assign.X.(*ast.TypeAssertExpr)
		if !ok || assert.Type != nil {
			return fmt.Errorf("unsupported type switch")
		}
		name, ok := identName(assert.X)
		if !ok {
			return fmt.Errorf("unsupported type switch tag")
		}
		tag = name
	default:
		return fmt.Errorf("unsupported type switch")
	}
	pad := strings.Repeat("  ", indent)
	fmt.Fprintf(b, "%sswitch (%s.tag) {\n", pad, tag)
	for _, stmt := range s.Body.List {
		cc, ok := stmt.(*ast.CaseClause)
		if !ok {
			return fmt.Errorf("unsupported type switch case")
		}
		if cc.List == nil {
			fmt.Fprintf(b, "%sdefault:\n", pad)
		}
		for _, e := range cc.List {
			id, ok := e.(*ast.Ident)
			if !ok {
				if sel, ok := e.(*ast.SelectorExpr); ok {
					id = sel.Sel
				} else {
					return parser.PosError(ctx.pos, "use a message type name", "unsupported type switch case %s", goExprText(e))
				}
			}
			fmt.Fprintf(b, "%scase %s:\n", pad, jsString(id.Name))
		}
		fmt.Fprintf(b, "%s{\n", pad)
		for _, st := range cc.Body {
			if err := g.stmt(b, st, ctx, indent+1); err != nil {
				return err
			}
		}
		fmt.Fprintf(b, "%s  break;\n%s}\n", pad, pad)
	}
	fmt.Fprintf(b, "%s}\n", pad)
	return nil
}

func (g *gen) expr(e ast.Expr, ctx exprCtx) (string, error) {
	switch e := e.(type) {
	case *ast.Ident:
		if ctx.locals[e.Name] {
			return e.Name, nil
		}
		if e.Name == "nil" {
			return "null", nil
		}
		return e.Name, nil
	case *ast.BasicLit:
		switch e.Kind {
		case token.STRING:
			v, err := strconv.Unquote(e.Value)
			if err != nil {
				return "", err
			}
			return jsString(v), nil
		case token.INT, token.FLOAT:
			return e.Value, nil
		case token.CHAR:
			v, err := strconv.Unquote(e.Value)
			if err != nil {
				return "", err
			}
			return jsString(v), nil
		default:
			return "", g.exprErr(ctx, "use a string, number, or rune literal", "unsupported literal %s", e.Value)
		}
	case *ast.SelectorExpr:
		if e.Sel.Name == "Error" {
			x, err := g.expr(e.X, ctx)
			if err != nil {
				return "", err
			}
			return x + ".message", nil
		}
		x, err := g.expr(e.X, ctx)
		if err != nil {
			return "", err
		}
		return x + "." + e.Sel.Name, nil
	case *ast.CallExpr:
		if id, ok := e.Fun.(*ast.Ident); ok && id.Name == "append" {
			return "", g.exprErr(ctx, "assign the append result to a field", "append is only supported in assignment")
		}
		if id, ok := e.Fun.(*ast.Ident); ok && id.Name == "len" && len(e.Args) == 1 {
			x, err := g.expr(e.Args[0], ctx)
			if err != nil {
				return "", err
			}
			return fmt.Sprintf("((%s) ?? []).length", x), nil
		}
		if sel, ok := e.Fun.(*ast.SelectorExpr); ok && sel.Sel.Name == "Error" {
			x, err := g.expr(sel.X, ctx)
			if err != nil {
				return "", err
			}
			return x + ".message", nil
		}
		if sel, ok := e.Fun.(*ast.SelectorExpr); ok {
			if id, ok := sel.X.(*ast.Ident); ok && id.Name == "js" {
				return g.jsCall(sel.Sel.Name, e.Args, ctx)
			}
		}
		if id, ok := e.Fun.(*ast.Ident); ok && !g.allowProcedures && g.procedureNames[id.Name] {
			return "", g.exprErr(ctx, "procedures are App-owned; emit an action to the App", "%s is an App procedure and cannot be called from a component", id.Name)
		}
		fun, err := g.expr(e.Fun, ctx)
		if err != nil {
			return "", err
		}
		args := make([]string, 0, len(e.Args))
		for _, a := range e.Args {
			v, err := g.expr(a, ctx)
			if err != nil {
				return "", err
			}
			args = append(args, v)
		}
		call := fmt.Sprintf("%s(%s)", fun, strings.Join(args, ", "))
		if ctx.async {
			return "await " + call, nil
		}
		return call, nil
	case *ast.BinaryExpr:
		x, err := g.expr(e.X, ctx)
		if err != nil {
			return "", err
		}
		y, err := g.expr(e.Y, ctx)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("%s %s %s", x, e.Op.String(), y), nil
	case *ast.UnaryExpr:
		if e.Op == token.AND {
			return "", g.exprErr(ctx, "use a pointer-valued model field or nil for optional props", "address-of expressions are not supported in views")
		}
		x, err := g.expr(e.X, ctx)
		if err != nil {
			return "", err
		}
		return e.Op.String() + x, nil
	case *ast.StarExpr:
		return g.expr(e.X, ctx)
	case *ast.ParenExpr:
		x, err := g.expr(e.X, ctx)
		if err != nil {
			return "", err
		}
		return "(" + x + ")", nil
	case *ast.CompositeLit:
		return g.composite(e, ctx)
	case *ast.FuncLit:
		return g.funcLit(e)
	default:
		return "", g.exprErr(ctx, "use a supported Go expression or move the work into Update", "unsupported expression %s", goExprText(e))
	}
}

func (g *gen) checkRoute(el *parser.Element) error {
	if !g.appModule {
		return parser.NodeError(el, "move the route link to the App view", "route links are only supported in the App view")
	}
	if el.Name != "a" {
		return parser.NodeError(el, "use <a href=\"/path\" route> for client-side navigation", "route is only supported on <a>")
	}
	if _, ok := g.app.Messages["LocationChanged"]; !ok {
		return parser.NodeError(el, "add a LocationChanged message to the app", "route links require a LocationChanged message")
	}
	return nil
}

func (g *gen) jsCall(name string, args []ast.Expr, ctx exprCtx) (string, error) {
	if !ctx.allowJS {
		return "", g.exprErr(ctx, "move js calls into Init, Update, or a command", "js.%s can only be used in Init, Update, or commands", name)
	}
	parts := make([]string, len(args))
	for i, arg := range args {
		v, err := g.expr(arg, ctx)
		if err != nil {
			return "", err
		}
		parts[i] = v
	}
	switch name {
	case "Alert":
		if len(parts) != 1 {
			return "", fmt.Errorf("js.Alert expects one argument")
		}
		return fmt.Sprintf("window.alert(%s)", parts[0]), nil
	case "Log":
		return "console.log(" + strings.Join(parts, ", ") + ")", nil
	case "SetTitle":
		if len(parts) != 1 {
			return "", fmt.Errorf("js.SetTitle expects one argument")
		}
		return fmt.Sprintf("(document.title = String(%s))", parts[0]), nil
	case "GetItem":
		if len(parts) != 1 {
			return "", fmt.Errorf("js.GetItem expects one argument")
		}
		return fmt.Sprintf("(localStorage.getItem(%s) ?? \"\")", parts[0]), nil
	case "SetItem":
		if len(parts) != 2 {
			return "", fmt.Errorf("js.SetItem expects two arguments")
		}
		return fmt.Sprintf("localStorage.setItem(%s, %s)", parts[0], parts[1]), nil
	case "RemoveItem":
		if len(parts) != 1 {
			return "", fmt.Errorf("js.RemoveItem expects one argument")
		}
		return fmt.Sprintf("localStorage.removeItem(%s)", parts[0]), nil
	case "Copy":
		if len(parts) != 1 {
			return "", fmt.Errorf("js.Copy expects one argument")
		}
		call := fmt.Sprintf("navigator.clipboard.writeText(%s)", parts[0])
		if ctx.async {
			call = "await " + call
		}
		return call, nil
	case "Focus":
		if len(parts) != 1 {
			return "", fmt.Errorf("js.Focus expects one argument")
		}
		return fmt.Sprintf("document.querySelector(%s)?.focus()", parts[0]), nil
	case "Navigate":
		if len(parts) != 1 {
			return "", fmt.Errorf("js.Navigate expects one argument")
		}
		if _, ok := g.app.Messages["LocationChanged"]; !ok {
			return "", g.exprErr(ctx, "add a LocationChanged message to the app", "js.Navigate requires a LocationChanged message")
		}
		return fmt.Sprintf("navigate(%s)", parts[0]), nil
	case "Replace":
		if len(parts) != 1 {
			return "", fmt.Errorf("js.Replace expects one argument")
		}
		if _, ok := g.app.Messages["LocationChanged"]; !ok {
			return "", g.exprErr(ctx, "add a LocationChanged message to the app", "js.Replace requires a LocationChanged message")
		}
		return fmt.Sprintf("replaceLocation(%s)", parts[0]), nil
	case "Back":
		if len(parts) != 0 {
			return "", fmt.Errorf("js.Back takes no arguments")
		}
		if _, ok := g.app.Messages["LocationChanged"]; !ok {
			return "", g.exprErr(ctx, "add a LocationChanged message to the app", "js.Back requires a LocationChanged message")
		}
		return "history.back()", nil
	case "Reload":
		if len(parts) != 0 {
			return "", fmt.Errorf("js.Reload takes no arguments")
		}
		return "location.reload()", nil
	default:
		return "", fmt.Errorf("unknown js function %s", name)
	}
}

func (g *gen) funcLit(e *ast.FuncLit) (string, error) {
	if e.Type.Params != nil && len(e.Type.Params.List) > 0 {
		return "", g.exprErr(exprCtx{pos: g.appPos(e.Pos())}, "remove the parameters from the command", "command functions cannot take parameters")
	}
	var b strings.Builder
	b.WriteString("async () => {\n")
	ctx := &exprCtx{async: true, allowJS: true}
	for _, st := range e.Body.List {
		if err := g.stmt(&b, st, ctx, 1); err != nil {
			return "", err
		}
	}
	b.WriteString("}")
	return b.String(), nil
}

func (g *gen) objectLiteral(e *ast.CompositeLit, ctx exprCtx) (string, error) {
	parts := make([]string, 0, len(e.Elts))
	for _, elt := range e.Elts {
		kv, ok := elt.(*ast.KeyValueExpr)
		if !ok {
			return "", g.exprErr(ctx, "write props fields as Name: value", "props literals must use keyed fields")
		}
		key, ok := identName(kv.Key)
		if !ok {
			return "", g.exprErr(ctx, "props field names must be identifiers", "props fields must be identifiers")
		}
		val, err := g.expr(kv.Value, ctx)
		if err != nil {
			return "", err
		}
		parts = append(parts, key+": "+val)
	}
	return "{" + strings.Join(parts, ", ") + "}", nil
}

func (g *gen) composite(e *ast.CompositeLit, ctx exprCtx) (string, error) {
	switch t := e.Type.(type) {
	case *ast.Ident:
		if g.propsTypes[t.Name] {
			return g.objectLiteral(e, ctx)
		}
		if _, ok := g.app.Messages[t.Name]; !ok {
			return "", g.exprErr(ctx, "declare the message struct in the prelude", "unknown message type %s", t.Name)
		}
		parts := []string{fmt.Sprintf("tag: %s", jsString(t.Name))}
		for _, elt := range e.Elts {
			kv, ok := elt.(*ast.KeyValueExpr)
			if !ok {
				return "", g.exprErr(ctx, "write message fields as Name: value", "message literals must use keyed fields")
			}
			key, ok := identName(kv.Key)
			if !ok {
				return "", g.exprErr(ctx, "message field names must be identifiers", "message fields must be identifiers")
			}
			val, err := g.expr(kv.Value, ctx)
			if err != nil {
				return "", err
			}
			parts = append(parts, key+": "+val)
		}
		return "{" + strings.Join(parts, ", ") + "}", nil
	case *ast.SelectorExpr:
		return g.objectLiteral(e, ctx)
	case *ast.ArrayType:
		parts := make([]string, 0, len(e.Elts))
		for _, elt := range e.Elts {
			v, err := g.expr(elt, ctx)
			if err != nil {
				return "", err
			}
			parts = append(parts, v)
		}
		return "[" + strings.Join(parts, ", ") + "]", nil
	default:
		return "", g.exprErr(ctx, "use a message literal or an array literal", "unsupported composite literal %s", goExprText(e))
	}
}

func (g *gen) temp() string {
	g.tempN++
	return fmt.Sprintf("__gothicErr%d", g.tempN)
}

func identName(e ast.Expr) (string, bool) {
	id, ok := e.(*ast.Ident)
	if !ok {
		return "", false
	}
	return id.Name, true
}

func isAppend(c *ast.CallExpr) bool {
	id, ok := c.Fun.(*ast.Ident)
	return ok && id.Name == "append" && len(c.Args) >= 2
}

func (g *gen) isErrorProcedure(c *ast.CallExpr) bool {
	id, ok := c.Fun.(*ast.Ident)
	if !ok {
		return false
	}
	for _, p := range g.app.Procedures {
		if p.Name == id.Name && p.ResultType == "" {
			return true
		}
	}
	return false
}

func singleModelParam(params string) (name, typ string, ok bool) {
	p := strings.TrimSpace(params)
	p = strings.TrimPrefix(p, "(")
	p = strings.TrimSuffix(p, ")")
	p = strings.TrimSpace(p)
	if p == "" || strings.Contains(p, ",") {
		return "", "", false
	}
	parts := strings.Fields(p)
	if len(parts) != 2 {
		return "", "", false
	}
	return parts[0], parts[1], true
}

func jsString(s string) string {
	b, err := json.Marshal(s)
	if err != nil {
		return `""`
	}
	return string(b)
}

func baseName(path string) string {
	if i := strings.LastIndexAny(path, `/\`); i >= 0 {
		return path[i+1:]
	}
	return path
}

func (g *gen) componentInit(comp *generator.Stateful) (string, bool, error) {
	init := comp.App.Init
	if init == nil {
		return "", false, nil
	}
	paramName := ""
	if init.Type.Params != nil {
		var params []*ast.Field
		for _, field := range init.Type.Params.List {
			params = append(params, field)
		}
		if len(params) > 1 {
			return "", false, parser.PosError(g.appPos(init.Pos()), "take zero parameters or one props parameter", "component %s: Init takes too many parameters", comp.Name)
		}
		if len(params) == 1 {
			field := params[0]
			if len(field.Names) == 0 {
				return "", false, parser.PosError(g.appPos(init.Pos()), "name the props parameter", "component %s: Init parameter must be named", comp.Name)
			}
			if comp.PropsType == "" {
				return "", false, parser.PosError(g.appPos(init.Pos()), "remove the Init parameter; the component has no props struct", "component %s: Init cannot take props without a props type", comp.Name)
			}
			typ := typeText(field.Type)
			if typ != comp.PropsType {
				return "", false, parser.PosError(g.appPos(init.Pos()), "match the props type "+comp.PropsType, "component %s: Init parameter has type %s, want %s", comp.Name, typ, comp.PropsType)
			}
			paramName = field.Names[0].Name
		}
	}
	g.initParam = paramName
	var b strings.Builder
	if err := g.emitInit(&b); err != nil {
		return "", false, err
	}
	return b.String(), paramName != "", nil
}

func (g *gen) constructorInfo(comp *generator.Stateful) (*ast.FuncDecl, bool, error) {
	if comp.Constructor == "" {
		return nil, false, nil
	}
	fn := comp.App.Commands[comp.Constructor]
	if fn == nil {
		return nil, false, parser.PosError(comp.View.NodePosition, "declare "+comp.Constructor+" in the prelude", "component %s: constructor %s not found", comp.Name, comp.Constructor)
	}
	var params []*ast.Field
	if fn.Type.Params != nil {
		params = append(params, fn.Type.Params.List...)
	}
	if len(params) > 1 {
		return nil, false, parser.PosError(g.appPos(fn.Pos()), "take zero parameters or one props parameter", "component %s: constructor takes too many parameters", comp.Name)
	}
	takesProps := false
	if len(params) == 1 {
		if len(params[0].Names) == 0 {
			return nil, false, parser.PosError(g.appPos(fn.Pos()), "name the constructor parameter", "component %s: constructor parameter must be named", comp.Name)
		}
		if comp.PropsType == "" {
			return nil, false, parser.PosError(g.appPos(fn.Pos()), "remove the constructor parameter; the component has no props struct", "component %s: constructor cannot take props without a props type", comp.Name)
		}
		if typ := typeText(params[0].Type); typ != comp.PropsType {
			return nil, false, parser.PosError(g.appPos(fn.Pos()), "match the props type "+comp.PropsType, "component %s: constructor parameter has type %s, want %s", comp.Name, typ, comp.PropsType)
		}
		takesProps = true
	}
	results := fn.Type.Results
	if results == nil || len(results.List) != 1 {
		return nil, false, parser.PosError(g.appPos(fn.Pos()), "return one "+comp.ModelType, "component %s: constructor must return %s", comp.Name, comp.ModelType)
	}
	if typ := typeText(results.List[0].Type); typ != comp.ModelType {
		return nil, false, parser.PosError(g.appPos(fn.Pos()), "return "+comp.ModelType, "component %s: constructor returns %s, want %s", comp.Name, typ, comp.ModelType)
	}
	return fn, takesProps, nil
}

func (g *gen) emitConstructor(b *strings.Builder, comp *generator.Stateful, fn *ast.FuncDecl, takesProps bool) error {
	param := ""
	if takesProps {
		param = fn.Type.Params.List[0].Names[0].Name
	}
	fmt.Fprintf(b, "function %s(%s) {\n", "new"+jsIdent(comp.Name), param)
	ctx := &exprCtx{}
	for _, st := range fn.Body.List {
		if err := g.stmt(b, st, ctx, 1); err != nil {
			return err
		}
	}
	b.WriteString("}\n\n")
	return nil
}

// GenerateComponents renders a JavaScript module with stateful component
// mount and create functions.
func GenerateComponents(components []*generator.Stateful, opts Options) ([]byte, error) {
	if len(components) == 0 {
		return []byte{}, nil
	}
	if opts.RuntimeURL == "" {
		opts.RuntimeURL = "/_gothic/runtime.js"
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gothic from %s. DO NOT EDIT.\n\n", baseName(opts.FileName))
	fmt.Fprintf(&b, "import { attrLocal, classToggleLocal, focusLocal, ifBlockLocal, listLocal, onLocal, textLocal } from %s;\n\n", jsString(opts.RuntimeURL))
	b.WriteString("function cloneInitial(value) {\n  return JSON.parse(JSON.stringify(value));\n}\n\n")
	b.WriteString("function readComponentState(root) {\n")
	b.WriteString("  const el = root.querySelector('script[data-gothic-component-state]');\n")
	b.WriteString("  if (!el) return null;\n")
	b.WriteString("  try { return JSON.parse(el.textContent || 'null'); } catch (_) { return null; }\n")
	b.WriteString("}\n\n")

	for _, comp := range components {
		if comp.App == nil || comp.View == nil {
			return nil, fmt.Errorf("component %s is missing its app or view", comp.Name)
		}
		if len(comp.View.ParamList) == 0 {
			return nil, parser.PosError(comp.View.NodePosition, "declare the model as the first parameter", "component %s must have a model parameter", comp.Name)
		}
		modelName := comp.View.ParamList[0].Name
		initial := "INITIAL_" + jsIdent(comp.Name)
		fmt.Fprintf(&b, "const %s = %s;\n\n", initial, comp.ModelJSON)

		propSig := ""
		if comp.PropsType != "" {
			propSig = ", props"
		}

		g := &gen{t: comp.View, app: comp.App, modelName: modelName, localHelpers: true, procedureNames: opts.ProcedureNames, propsTypes: opts.PropsTypes}
		updatePropParam, err := g.updatePropsParamName(comp)
		if err != nil {
			return nil, wrapFile(comp.Name, err)
		}
		g.updatePropsParam = updatePropParam
		if updatePropParam == "m" || updatePropParam == "msg" {
			return nil, parser.PosError(g.appPos(comp.App.Update.Pos()), "rename the props parameter", "component %s: Update props parameter %q conflicts with a generated name", comp.Name, updatePropParam)
		}
		ctorFn, ctorTakesProps, err := g.constructorInfo(comp)
		if err != nil {
			return nil, wrapFile(comp.Name, err)
		}
		ctorCall := ""
		if comp.Constructor != "" {
			ctorCall = "new" + jsIdent(comp.Name)
			if ctorTakesProps {
				ctorCall += "(props)"
			} else {
				ctorCall += "()"
			}
			if err := g.emitConstructor(&b, comp, ctorFn, ctorTakesProps); err != nil {
				return nil, wrapFile(comp.Name, err)
			}
		}
		var bindings strings.Builder
		if err := g.emitViewBindings(&bindings); err != nil {
			return nil, wrapFile(comp.Name, err)
		}

		var renderCall strings.Builder
		g.emitRender(&renderCall)

		var updateFn strings.Builder
		if err := g.emitUpdate(&updateFn); err != nil {
			return nil, wrapFile(comp.Name, err)
		}

		initFn, initTakesProps, err := g.componentInit(comp)
		if err != nil {
			return nil, wrapFile(comp.Name, err)
		}

		fmt.Fprintf(&b, "export function %s(root%s, __gothicParentDispatch) {\n", comp.MountFunc, propSig)
		if ctorCall != "" {
			fmt.Fprintf(&b, "  let %s = readComponentState(root) || %s;\n", modelName, ctorCall)
		} else {
			fmt.Fprintf(&b, "  let %s = readComponentState(root) || cloneInitial(%s);\n", modelName, initial)
		}
		b.WriteString("  let alive = true;\n")
		b.WriteString("  function emit(msg) {\n    if (__gothicParentDispatch && msg != null) __gothicParentDispatch(msg);\n  }\n")
		b.WriteString(indentJS(bindings.String(), "  "))
		b.WriteString(indentJS(renderCall.String(), "  "))
		b.WriteString(indentJS(updateFn.String(), "  "))
		b.WriteString(indentJS(initFn, "  "))
		var commandFns strings.Builder
		for name := range comp.App.ReferencedCommands {
			fn := comp.App.Commands[name]
			if fn == nil {
				continue
			}
			if err := g.emitCommand(&commandFns, fn); err != nil {
				return nil, wrapFile(comp.Name, err)
			}
		}
		b.WriteString(indentJS(commandFns.String(), "  "))
		dispatchArgs := modelName + ", msg"
		if updatePropParam != "" {
			dispatchArgs += ", props"
		}
		fmt.Fprintf(&b, "  function dispatch(msg) {\n    if (!alive) return;\n    const result = update(%s);\n    %s = result[0];\n    render(%s);\n    if (result[1]) run(result[1]);\n  }\n", dispatchArgs, modelName, modelName)
		b.WriteString("  async function run(cmd) {\n    if (!cmd || !alive) return;\n    const msg = await cmd();\n    if (alive && msg) dispatch(msg);\n  }\n")
		fmt.Fprintf(&b, "  render(%s);\n", modelName)
		if initFn != "" {
			if initTakesProps {
				b.WriteString("  run(init(props));\n")
			} else {
				b.WriteString("  run(init());\n")
			}
		}
		if comp.PropsType == "" {
			b.WriteString("  return { updateProps() {\n    if (!alive) return;\n")
			fmt.Fprintf(&b, "    render(%s);\n", modelName)
		} else {
			b.WriteString("  return { updateProps(nextProps) {\n    if (!alive) return;\n    let changed = false;\n")
			for _, field := range comp.Props {
				fmt.Fprintf(&b, "    if (!Object.is(props.%s, nextProps.%s)) changed = true;\n", field.Name, field.Name)
			}
			b.WriteString("    if (changed) { props = nextProps; dispatch({tag: \"PropsChanged\"}); } else { render(" + modelName + "); }\n")
		}
		b.WriteString("  }, destroy() { alive = false; } };\n}\n\n")

		cg := &gen{t: comp.View, app: comp.App, modelName: modelName, localHelpers: true, procedureNames: opts.ProcedureNames, propsTypes: opts.PropsTypes}
		locals := map[string]bool{}
		for _, p := range comp.Props {
			locals[p.Name] = true
		}
		var dom strings.Builder
		var ignored []itemBinding
		rootVar, err := cg.emitDOM(&dom, comp.View.Children[0].(*parser.Element), locals, &ignored)
		if err != nil {
			return nil, wrapFile(comp.Name, err)
		}

		fmt.Fprintf(&b, "export function %s(id%s) {\n", comp.CreateFunc, propSig)
		b.WriteString("  const wrapper = document.createElement('div');\n")
		fmt.Fprintf(&b, "  wrapper.setAttribute('data-gothic-component', %s);\n", jsString(comp.Name))
		b.WriteString("  wrapper.setAttribute('data-gothic-component-id', id);\n")
		if ctorCall != "" {
			fmt.Fprintf(&b, "  const %s = %s;\n", modelName, ctorCall)
		} else {
			fmt.Fprintf(&b, "  const %s = cloneInitial(%s);\n", modelName, initial)
		}
		b.WriteString(indentJS(dom.String(), "  "))
		fmt.Fprintf(&b, "  wrapper.appendChild(%s);\n", rootVar)
		b.WriteString("  return wrapper;\n}\n\n")
	}
	return []byte(b.String()), nil
}

func indentJS(s, prefix string) string {
	if s == "" {
		return ""
	}
	lines := strings.Split(s, "\n")
	for i, line := range lines {
		if line != "" {
			lines[i] = prefix + line
		}
	}
	return strings.Join(lines, "\n")
}

func jsIdent(name string) string {
	var b strings.Builder
	for i, r := range name {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || r == '_' || (i > 0 && r >= '0' && r <= '9') {
			b.WriteRune(r)
		} else {
			b.WriteRune('_')
		}
	}
	return b.String()
}

func jsTitle(name string) string {
	if name == "" {
		return ""
	}
	return strings.ToUpper(name[:1]) + name[1:]
}
